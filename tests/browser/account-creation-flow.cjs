const assert = require('node:assert/strict');
module.exports = async function ({ page, data, control, tab, artifactDir, results }) {
  await tab(page, 'Admin');
  const form = page.getByRole('form', { name: 'New teammate' });
  const create = form.getByRole('button', { name: 'Create user', exact: true });
  await form.getByLabel('Email', { exact: true }).fill('create-test@example.test');
  await form.getByLabel('Full Name', { exact: true }).fill('Create Test');
  await form.getByLabel('Temporary Password', { exact: true }).fill('short');
  await create.click(); await page.getByRole('alert').filter({ hasText: '8-72' }).waitFor();
  assert.equal(control.creationCalls?.length || 0, 0);
  await form.getByLabel('Temporary Password', { exact: true }).fill('fixture-custom-creation-password');
  await form.getByLabel('QA Fixture', { exact: true }).check();
  control.loseCreationAck = true;
  await create.click(); await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  assert.equal(control.authCreationWrites, 1);
  const initial = control.creationCalls[0];
  assert.equal(initial.username, 'create-test'); assert.deepEqual(initial.productIds, ['qa-fixture']);
  assert.equal(await create.isDisabled(), true);
  assert.equal(await form.getByLabel('Email', { exact: true }).isDisabled(), true);
  const stored = await page.evaluate(() => Object.values(sessionStorage).join(' '));
  assert.equal(stored.includes('fixture-custom-creation-password'), false);
  await page.getByRole('article', { name: initial.email, exact: true }).waitFor();
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(async () => { window.scrollTo(0, 0); await new Promise(requestAnimationFrame); });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    if ([320,1440].includes(width)) await page.screenshot({ path: `${artifactDir}/account-creation-${width}.png`, fullPage: true });
  }
  await page.reload(); await tab(page, 'Admin');
  await page.getByRole('button', { name: 'Recover account creation', exact: true }).click();
  await page.getByText('Created create-test@example.test. Temporary password: fixture-custom-creation-password', { exact: true }).waitFor();
  const { tempPassword, ...safe } = initial;
  assert.deepEqual(control.creationCalls.at(-1), safe); assert.equal(control.authCreationWrites, 1);
  assert.equal(data.profiles_with_products.filter((row) => row.email === initial.email).length, 1);
  assert.equal(await form.getByLabel('Temporary Password', { exact: true }).inputValue(), '');
  await form.getByLabel('Email', { exact: true }).fill(initial.email);
  control.expectedCreationRejections = 1;
  await create.click(); await page.getByRole('alert').filter({ hasText: 'already exists' }).waitFor();
  assert.equal(await form.getByLabel('Email', { exact: true }).inputValue(), initial.email);
  assert.equal(control.authCreationWrites, 1);
  await form.getByLabel('Email', { exact: true }).fill('new-admin@example.test');
  await form.getByLabel('Role', { exact: true }).selectOption('admin');
  control.creationUncertain = true; control.expectedCreationRejections = 1;
  await create.click(); await page.getByRole('alert').filter({ hasText: 'not confirmed' }).waitFor();
  control.expectedCreationRejections = 1;
  await page.getByRole('button', { name: 'Recover account creation', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'not confirmed' }).waitFor(); assert.equal(control.authCreationWrites, 2);
  control.creationUncertain = false;
  await page.getByRole('button', { name: 'Recover account creation', exact: true }).click();
  await page.getByText('Created new-admin@example.test. Temporary password: fixture-generated-creation-password', { exact: true }).waitFor();
  assert.deepEqual(control.creationCalls.at(-1).productIds, []);
  await page.getByRole('article', { name: 'new-admin@example.test', exact: true }).getByText('admin', { exact: true }).waitFor();
  assert.equal(control.authCreationWrites, 2);
  results.push('Account creation: validated custom/generated passwords, exact recovery across reload without plaintext storage or a second Auth create, duplicate rejection/draft retention, admin/member assignments and 320-1440px layouts');
};
