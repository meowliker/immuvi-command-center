const assert = require('node:assert/strict');
module.exports = async function ({ page, data, control, tab, artifactDir, results }) {
  const target = { ...data.profiles_with_products[0], id: '22222222-2222-4222-8222-222222222222', email: 'account-test@example.test', role: 'member', product_ids: ['qa-fixture'] };
  data.profiles_with_products.push(target);
  data.account_audit = Array.from({ length: 51 }, (_, i) => ({ id: String(100 - i), action: 'qa_user_role', createdAt: new Date().toISOString(), actorId: data.profiles[0].id, targetId: target.id, email: `history-${i}@example.test` }));
  await tab(page, 'Admin');
  const row = page.getByRole('article', { name: target.email, exact: true });
  const button = (name) => row.getByRole('button', { name, exact: true });
  await row.waitFor();
  const self = page.getByRole('article', { name: data.profiles[0].email, exact: true });
  for (const name of ['Reset password', 'Deactivate', 'Delete account']) assert.equal(await self.getByRole('button', { name, exact: true }).isDisabled(), true);
  const history = page.getByRole('region', { name: 'Account activity' });
  await history.getByText('history-49@example.test', { exact: true }).waitFor();
  assert.equal(await history.getByText('history-50@example.test', { exact: true }).count(), 0);
  await history.getByRole('button', { name: 'Load earlier activity', exact: true }).click();
  await history.getByText('history-50@example.test', { exact: true }).waitFor();
  control.loseAccountAck = true;
  await button('Reset password').click();
  await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  assert.equal(control.authAccountWrites, 1);
  const reset = control.accountCalls.at(-1);
  assert.equal(await button('Make admin').isDisabled(), true);
  const stored = await page.evaluate(() => Object.values(sessionStorage).join(' '));
  assert.equal(stored.includes('fixture-temporary-password'), false);
  await page.reload(); await tab(page, 'Admin');
  await page.getByRole('button', { name: 'Recover account operation', exact: true }).click();
  await page.getByText(`Temporary password for ${target.email}: fixture-temporary-password`, { exact: true }).waitFor();
  assert.deepEqual(control.accountCalls.at(-1), reset); assert.equal(control.authAccountWrites, 1);
  await button('Deactivate').click();
  await button('Reactivate').waitFor();
  control.accountUncertain = true; control.expectedAccountRejections = 1;
  await button('Reactivate').click();
  await page.getByRole('alert').filter({ hasText: 'not confirmed' }).waitFor();
  const reactivate = control.accountCalls.at(-1), writes = control.authAccountWrites;
  control.expectedAccountRejections = 1;
  await page.getByRole('button', { name: 'Recover account operation', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'not confirmed' }).waitFor();
  assert.equal(control.authAccountWrites, writes);
  control.resolveAccount = true; control.accountUncertain = false;
  await page.getByRole('button', { name: 'Recover account operation', exact: true }).click();
  await button('Deactivate').waitFor(); assert.deepEqual(control.accountCalls.at(-1), reactivate);
  await button('Delete account').click();
  const dialog = page.getByRole('dialog', { name: 'Delete account', exact: true });
  assert.equal(await dialog.getByRole('button', { name: 'Delete account permanently', exact: true }).isDisabled(), true);
  await dialog.getByLabel('Type account email').fill('wrong@example.test');
  assert.equal(await dialog.getByRole('button', { name: 'Delete account permanently', exact: true }).isDisabled(), true);
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
    if ([320,1440].includes(width)) await page.screenshot({ path: `${artifactDir}/account-delete-${width}.png`, fullPage: true });
  }
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click(); assert.equal(control.authAccountWrites, writes);
  await button('Delete account').click(); await dialog.getByLabel('Type account email').fill(target.email);
  target.accessGeneration++; control.expectedAccountRejections = 1;
  await dialog.getByRole('button', { name: 'Delete account permanently', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'User access changed' }).waitFor();
  assert.equal(await dialog.getByLabel('Type account email').inputValue(), target.email);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.waitForLoadState('networkidle');
  await button('Delete account').click(); await dialog.getByLabel('Type account email').fill(target.email);
  control.loseAccountAck = true;
  await dialog.getByRole('button', { name: 'Delete account permanently', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const deletion = control.accountCalls.at(-1);
  await page.reload(); await tab(page, 'Admin');
  await page.getByRole('button', { name: 'Recover account operation', exact: true }).click();
  await page.getByText('Account deleted.', { exact: true }).waitFor();
  assert.deepEqual(control.accountCalls.at(-1), deletion);
  assert.equal(await row.count(), 0); assert.equal(control.authAccountWrites, 4);
  await history.getByText('delete user', { exact: true }).waitFor();
  assert.equal(data.products.length, 2); assert.equal(data.ads.length, 1);
  results.push('Account operations: self guards, reset lost-ack replay without a second reset or stored plaintext credential, deactivate/reactivate fail-closed recovery, typed delete/cancel/stale protection and deleted-user recovery, paginated account history and 320-1440px dialogs');
};
