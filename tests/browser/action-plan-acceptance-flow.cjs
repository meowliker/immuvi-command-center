const assert = require('node:assert/strict');
module.exports = async function testPlanAcceptance({ page, context, data, control, emit, tab, artifactDir, results }) {
  const stamp = data.manual_actions[0].updated_at;
  data.manual_actions.push({ id: 'STANDALONE', product_id: 'qa-fixture', live_status: 'Untested', payload: { title: 'Standalone QA task' }, created_at: stamp, updated_at: stamp });
  await tab(page, 'Action Plan');
  const status = page.getByLabel('Status for QA creative', { exact: true });
  await status.waitFor();
  await page.waitForLoadState('networkidle');
  assert.equal(await status.inputValue(), 'Untested');
  const snapshot = data.ads[0].updated_at;
  data.ads[0].status = 'Winner'; data.ads[0].updated_at = new Date(Date.parse(snapshot) + 1000).toISOString();
  control.expectedWorkflowRejections = 1;
  await status.selectOption('Testing');
  await page.getByRole('alert').filter({ hasText: 'Task changed' }).waitFor();
  assert.equal(data.ads[0].status, 'Winner', 'A stale quick edit must not replace the newer status');
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('select[aria-label="Status for QA creative"]')?.value === 'Winner');
  await status.selectOption('Testing');
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  assert.equal(data.ads[0].status, 'Testing');
  await page.getByLabel('Status for Standalone QA task', { exact: true }).selectOption('In Production');
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  const standalone = data.manual_actions.find((row) => row.id === 'STANDALONE');
  assert.equal(standalone.live_status, 'In Production');
  await page.getByLabel('Due date for Standalone QA task', { exact: true }).fill('2026-10-10');
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  await page.getByLabel('Due date for Standalone QA task', { exact: true }).fill('');
  await page.getByText('Due date cleared.', { exact: true }).waitFor();
  assert.equal(standalone.payload.dueDate, '');
  assert.deepEqual(data.activity_events.filter((event) => event.action_id === 'STANDALONE').map((event) => event.event_type), ['status_changed', 'due_changed', 'due_changed']);
  const before = control.clickupCalls.length;
  const rejectAck = async (route) => route.fulfill({ status: 200, contentType: 'application/json', body: 'null' });
  await context.route(/\/rest\/v1\/rpc\/qa_plan_edit$/, rejectAck);
  await status.selectOption('Winner');
  await page.getByRole('alert').filter({ hasText: 'Save could not be verified' }).waitFor();
  assert.equal(await status.inputValue(), 'Testing'); assert.equal(control.clickupCalls.length, before);
  await context.unroute(/\/rest\/v1\/rpc\/qa_plan_edit$/, rejectAck);
  data.ads[0].status = 'Winner'; emit('ads', 'UPDATE', data.ads[0]);
  await page.getByRole('button', { name: 'Variations view', exact: true }).click();
  await page.getByRole('button', { name: 'Create variations', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Variation Lab: QA creative', exact: true });
  await dialog.getByLabel('Editor brief', { exact: true }).fill('Retain after missing acknowledgement');
  let requests = 0;
  control.loseSpawnAck = true;
  await context.route(/\/rest\/v1\/rpc\/qa_tracker_spawn$/, async (route) => {
    requests++;
    await route.fallback();
  });
  await dialog.getByRole('button', { name: 'Create 1 variations', exact: true }).click();
  await dialog.getByText(/Creation may have completed/).waitFor();
  assert.equal(await dialog.getByRole('button', { name: 'Create 1 variations', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByLabel('Editor brief', { exact: true }).inputValue(), 'Retain after missing acknowledgement');
  assert.equal(requests, 1);
  await page.screenshot({ path: `${artifactDir}/action-plan-uncertain-variation.png` });
  await dialog.getByRole('button', { name: 'Close Variation Lab', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.locator('[data-variation-group="AD-1"]').waitFor();
  assert.equal(data.ads.filter((ad) => ad.parent_ad_id === 'AD-1').length, 1);
  assert.equal(control.clickupCalls.length, before);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Final Action Plan acceptance: stale quick-edit rejection, fresh retry, standalone atomic workflow/history and date clearing, unverifiable-save rejection without remote push, retained uncertain variation draft with repeat blocked and Matrix refresh reconciliation');
};
