const assert = require('node:assert/strict');
const resizeColumn = require('./plan-column-resize.cjs');
module.exports = async function testPlanAge({ page, data, emit, tab, artifactDir, results }) {
  const now = new Date(2026, 8, 16, 12).getTime(), day = 86_400_000;
  await page.clock.setFixedTime(now);
  const ad = data.ads[0], action = data.manual_actions[0];
  Object.assign(ad, { status: 'QA', created_at: new Date(now - 40 * day).toISOString(), last_status_change_at: now - 3.2 * day });
  for (const [id, status, days] of [['close', 'QA', 3.1], ['review', 'Testing', 8], ['terminal', 'Winner', 12], ['future', 'QA', -1]]) {
    data.ads.push({ ...structuredClone(ad), id, format_name: id, status, last_status_change_at: now - days * day });
    data.manual_actions.push({ ...structuredClone(action), id: `action-${id}`, payload: { adId: id, title: id } });
  }
  data.manual_actions.push({ id: 'action-missing', product_id: 'qa-fixture', live_status: 'Paused', payload: { title: 'missing' }, created_at: null, updated_at: null });
  await tab(page, 'Action Plan');
  await page.getByLabel('Select terminal', { exact: true }).waitFor();
  const header = page.locator('[data-plan-column="age"]');
  const ids = () => page.locator('[data-plan-row]').evaluateAll((els) => els.map((el) => el.dataset.planRow));
  assert.equal(await page.locator('[data-plan-cell="status"] [data-plan-age]').count(), 0);
  assert.equal(await page.locator('[data-plan-cell="age"] [data-plan-age]').count(), 6);
  await page.getByLabel('Select close', { exact: true }).check();
  await header.getByRole('button', { name: 'Age in status', exact: true }).click();
  assert.equal(await header.getAttribute('aria-sort'), 'ascending');
  assert.deepEqual(await ids(), ['action-future', 'action-close', 'ACTION-1', 'action-review', 'action-terminal', 'action-missing']);
  await header.getByRole('button').click();
  assert.equal(await header.getAttribute('aria-sort'), 'descending');
  assert.deepEqual(await ids(), ['action-terminal', 'action-review', 'ACTION-1', 'action-close', 'action-future', 'action-missing']);
  const close = data.ads.find((row) => row.id === 'close'); close.last_status_change_at = now - 20 * day; emit('ads', 'UPDATE', close);
  await page.waitForFunction(() => document.querySelector('[data-plan-row]')?.getAttribute('data-plan-row') === 'action-close');
  assert.equal(await page.getByLabel('Select close', { exact: true }).isChecked(), true);
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Show Status', { exact: true }).uncheck();
  await dialog.getByRole('button', { name: 'Move Age in status up', exact: true }).click();
  await dialog.getByLabel('New view name', { exact: true }).fill('Age review');
  await dialog.getByRole('button', { name: 'Save as new view', exact: true }).click(); await dialog.waitFor({ state: 'detached' });
  await resizeColumn(page, 'Age in status', 120);
  const savedId = await page.getByLabel('Action Plan saved view', { exact: true }).inputValue();
  assert.equal(await page.locator('[data-plan-column="status"]').count(), 0);
  assert.ok(Math.abs((await header.boundingBox()).width - 200) < 2);
  await page.getByRole('button', { name: 'Review testing for review', exact: true }).click();
  await dialog.getByRole('heading', { name: 'Day 7 testing review', exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close testing review', exact: true }).click();
  await page.screenshot({ path: `${artifactDir}/action-plan-age-desktop.png`, fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForFunction((id) => document.querySelector('[aria-label="Action Plan saved view"]')?.value === id, savedId);
  assert.ok(Math.abs((await header.boundingBox()).width - 200) < 2);
  assert.equal(await page.locator('[data-plan-column="status"]').count(), 0);
  assert.deepEqual(await page.locator('[data-plan-column]').evaluateAll((els) => els.slice(0, 3).map((el) => el.dataset.planColumn)), ['cb', 'source', 'title']);
  const savedColumns = data.profiles[0].ap_col_state.qa_next.views.find((view) => view.id === savedId).columns;
  assert.ok(savedColumns.findIndex((column) => column.key === 'age') < savedColumns.findIndex((column) => column.key === 'status'));
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  await dialog.getByLabel('Show Age in status', { exact: true }).uncheck();
  await dialog.getByRole('button', { name: 'Save layout', exact: true }).click(); await dialog.waitFor({ state: 'detached' });
  assert.equal(await header.count(), 0); assert.equal(await page.locator('[data-plan-cell] [data-plan-age]').count(), 0);
  await page.getByLabel('Action Plan saved view', { exact: true }).selectOption('default'); await header.waitFor();
  await page.setViewportSize({ width: 390, height: 844 });
  await header.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-age-mobile.png`, fullPage: true });
  await page.getByLabel('Action Plan saved view', { exact: true }).selectOption(savedId);
  await page.waitForFunction(() => !document.querySelector('[data-plan-column="age"]'));
  assert.equal(data.ads.length, 5); assert.equal(data.manual_actions.length, 6);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Dedicated Age column: precise ascending/descending sort, missing-last, realtime reorder without losing selection, checkpoint access with hidden Status, saved width/order/visibility, reload and responsive table');
};
