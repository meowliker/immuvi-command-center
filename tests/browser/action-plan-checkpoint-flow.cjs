const assert = require('node:assert/strict');
module.exports = async function testPlanCheckpoint({ page, data, control, emit, tab, artifactDir, results }) {
  const day = 86_400_000, now = new Date(2026, 8, 16, 12).getTime();
  control.checkpointNow = now;
  control.expectedCheckpointRejections = 2;
  await page.clock.setFixedTime(now);
  const ad = data.ads[0], act = data.manual_actions[0];
  Object.assign(ad, { status: 'Testing', last_status_change_at: now - 8 * day, created_at: new Date(now - 40 * day).toISOString(), updated_at: new Date(now - day).toISOString(), testing_defer_count: 0, testing_deferred_at: null, clickup_task_id: 'qa-review-1' });
  act.updated_at = ad.updated_at; act.payload._clickupId = ad.clickup_task_id;
  for (const [name, days] of [['Final review', 15], ['Stale review', 9], ['Boundary review', 13]]) {
    data.ads.push({ ...structuredClone(ad), id: name, format_name: name, last_status_change_at: now - days * day, clickup_task_id: `qa-${days}` });
    data.manual_actions.push({ ...structuredClone(act), id: `action-${days}`, payload: { adId: name, title: name, _clickupId: `qa-${days}` } });
  }
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await tab(page, 'Action Plan');
  const open = (title) => page.getByRole('button', { name: `Review testing for ${title}`, exact: true }).click();
  const dialog = page.getByRole('dialog');
  const save = () => dialog.getByRole('button', { name: 'Save testing review', exact: true }).click();
  const close = () => dialog.getByRole('button', { name: 'Close testing review', exact: true }).click();
  const pushes = () => control.clickupCalls.filter((call) => call.operation === 'push-creative').length;
  await open('QA creative');
  assert.equal(await dialog.getByRole('button', { name: 'Save testing review', exact: true }).isDisabled(), true);
  await dialog.getByRole('radio', { name: 'Needs more testing (+7 days)', exact: true }).check();
  await close(); assert.equal(data.activity_events.length, 0);
  await open('QA creative');
  await dialog.getByRole('radio', { name: 'Needs more testing (+7 days)', exact: true }).check();
  assert.equal(await dialog.getByLabel('Update ClickUp', { exact: true }).count(), 0);
  await page.screenshot({ path: `${artifactDir}/action-plan-review-desktop.png`, fullPage: true });
  control.holdReview = true;
  await save();
  for (let i = 0; !control.releaseReview && i < 100; i++) await new Promise((resolve) => setTimeout(resolve, 10));
  assert.equal(typeof control.releaseReview, 'function');
  assert.equal(await dialog.getByRole('button', { name: 'Close testing review', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole('radio', { name: 'Winner', exact: true }).isDisabled(), true);
  control.releaseReview(); control.releaseReview = null;
  await dialog.waitFor({ state: 'detached' });
  await page.locator('[data-plan-row="ACTION-1"] [data-checkpoint="snoozed"]').waitFor();
  assert.equal(ad.testing_defer_count, 1); assert.equal(ad.status, 'Testing'); assert.equal(pushes(), 0);
  await page.reload({ waitUntil: 'networkidle' });
  await page.locator('[data-plan-row="ACTION-1"] [data-checkpoint="snoozed"]').waitFor();
  assert.equal(await page.getByRole('button', { name: 'Review testing for QA creative', exact: true }).count(), 0);

  await page.getByRole('button', { name: 'Pipeline view', exact: true }).click();
  await open('Final review');
  assert.equal(await dialog.getByRole('radio', { name: 'Needs more testing (+7 days)', exact: true }).count(), 0);
  await dialog.getByRole('radio', { name: 'Loser', exact: true }).check();
  await dialog.getByLabel('Update ClickUp', { exact: true }).uncheck();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-review-mobile.png`, fullPage: true });
  await save(); await dialog.waitFor({ state: 'detached' });
  assert.equal(data.ads[1].status, 'Loser'); assert.equal(pushes(), 0);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Table view', exact: true }).click();

  await open('Stale review');
  await dialog.getByRole('radio', { name: 'Winner', exact: true }).check();
  const stale = data.ads[2]; stale.updated_at = new Date(now + 1).toISOString(); stale.meta.notes = 'Concurrent change';
  emit('ads', 'UPDATE', stale);
  await save();
  await dialog.getByRole('alert').filter({ hasText: 'Creative changed' }).waitFor();
  assert.equal(await dialog.getByRole('radio', { name: 'Winner', exact: true }).isChecked(), true);
  assert.equal(stale.status, 'Testing'); assert.equal(pushes(), 0);
  await close();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await page.getByRole('button', { name: 'Refresh', exact: true }).waitFor();
  await open('Stale review');
  await dialog.getByRole('radio', { name: 'Winner', exact: true }).check();
  control.clickupFailure = true;
  await save(); await dialog.waitFor({ state: 'detached' });
  await page.getByRole('status').filter({ hasText: 'Testing decision saved in QA: Winner. ClickUp pending:' }).waitFor();
  assert.equal(stale.status, 'Winner'); assert.equal(stale.meta.notes, 'Concurrent change'); assert.equal(pushes(), 1);
  control.clickupFailure = false;

  await open('Boundary review');
  await dialog.getByRole('radio', { name: 'Needs more testing (+7 days)', exact: true }).check();
  control.checkpointNow += 2 * day;
  await page.clock.setFixedTime(control.checkpointNow);
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await save();
  await dialog.getByRole('alert').filter({ hasText: 'Testing can only be snoozed once' }).waitFor();
  assert.equal(data.ads[3].testing_defer_count, 0);
  await close(); await open('Boundary review');
  assert.equal(await dialog.getByRole('radio', { name: 'Needs more testing (+7 days)', exact: true }).count(), 0);
  await dialog.getByRole('radio', { name: 'Scale', exact: true }).check();
  await dialog.getByLabel('Update ClickUp', { exact: true }).uncheck();
  await save(); await dialog.waitFor({ state: 'detached' });
  assert.equal(data.ads[3].status, 'Scale'); assert.equal(data.activity_events.length, 4);
  assert.deepEqual(control.rejectedCheckpoints, ['Creative changed. Close and reopen the testing review.', 'Testing can only be snoozed once at the first review']);
  assert.equal(control.expectedCheckpointRejections, 0);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Testing checkpoint cancel/save, single snooze and reload, final decisions, busy guards, stale snapshot retention, remote failure with local preservation, phase rollover, pipeline entry and mobile/desktop dialog');
};
