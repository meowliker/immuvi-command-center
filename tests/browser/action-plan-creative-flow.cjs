const assert = require('node:assert/strict');
module.exports = async function testPlanCreative({ page, context, data, control, emit, tab, artifactDir, results }) {
  const ad = data.ads[0], action = data.manual_actions[0];
  ad.clickup_task_id = 'qa-edit-task'; action.payload._clickupId = ad.clickup_task_id;
  ad.meta.notes = 'Original notes'; ad.meta.creativeHypothesis = 'Original hypothesis';
  await tab(page, 'Action Plan');
  const row = page.locator('[data-plan-row="ACTION-1"]');
  await row.getByRole('button', { name: 'Rename QA creative', exact: true }).click();
  await row.getByLabel('Task name', { exact: true }).fill('');
  await row.getByRole('button', { name: 'Save task name', exact: true }).click();
  await row.getByRole('alert').waitFor();
  await row.getByLabel('Task name', { exact: true }).fill('Discarded title');
  await row.getByRole('button', { name: 'Cancel rename', exact: true }).click();
  assert.equal(ad.format_name, 'QA creative');
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await row.getByRole('button', { name: 'Rename QA creative', exact: true }).click();
  await row.getByLabel('Task name', { exact: true }).fill('Renamed task');
  control.clickupFailure = true;
  await row.getByRole('button', { name: 'Save task name', exact: true }).click();
  await page.getByText('Saved in QA. ClickUp fields pending: Synthetic ClickUp outage', { exact: true }).waitFor();
  assert.equal(ad.format_name, 'Renamed task'); assert.equal(action.payload.title, 'Renamed task');
  assert.equal(await row.getByLabel('Task name', { exact: true }).count(), 0);
  control.clickupFailure = false;
  await row.getByRole('button', { name: 'Renamed task', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.locator('summary').filter({ hasText: /^Creative details$/ }).click();
  await dialog.getByLabel('Creative name', { exact: true }).waitFor();
  assert.equal(await dialog.getByLabel('Status', { exact: true }).count(), 1);
  assert.equal(await dialog.getByText('Custom fields', { exact: true }).count(), 0);
  await dialog.getByLabel('Creative name', { exact: true }).fill('Edited from Action Plan');
  await dialog.getByLabel('Angle', { exact: true }).selectOption('');
  await dialog.getByLabel('Ad type', { exact: true }).selectOption('Photo');
  await dialog.getByLabel('Funnel stage', { exact: true }).selectOption('BOF');
  await dialog.getByLabel('Hook type', { exact: true }).fill('Question');
  await dialog.getByLabel('Drive link', { exact: true }).fill('https://example.test/drive');
  await dialog.getByRole('textbox', { name: 'Creative hypothesis', exact: true }).fill('Revised hypothesis');
  await dialog.getByRole('textbox', { name: 'Notes', exact: true }).fill('');
  emit('ads', 'UPDATE', ad);
  await page.waitForTimeout(350);
  assert.equal(await dialog.getByLabel('Creative name', { exact: true }).inputValue(), 'Edited from Action Plan');
  await dialog.getByLabel('Update linked ClickUp task', { exact: true }).uncheck();
  const writeCount = () => control.clickupCalls.filter((call) => call.operation !== 'plan-statuses').length;
  const count = writeCount();
  await page.screenshot({ path: `${artifactDir}/action-plan-creative-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-creative-mobile.png`, fullPage: true });
  await dialog.getByRole('button', { name: 'Save creative', exact: true }).click();
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(writeCount(), count);
  assert.equal(ad.angle, ''); assert.equal(action.payload.sourceAngle, '');
  assert.equal(ad.ad_type, 'Photo'); assert.equal(ad.meta.hookType, 'Question'); assert.equal(ad.meta.notes, '');
  assert.equal(ad.meta.creativeHypothesis, 'Revised hypothesis'); assert.equal(ad.status, 'Untested');
  await page.reload({ waitUntil: 'networkidle' });
  await row.getByRole('button', { name: 'Edited from Action Plan', exact: true }).click();
  await dialog.locator('summary').filter({ hasText: /^Creative details$/ }).click();
  await dialog.getByLabel('Creative name', { exact: true }).waitFor();
  assert.equal(await dialog.getByRole('textbox', { name: 'Notes', exact: true }).inputValue(), '');
  assert.equal(await dialog.getByLabel('Drive link', { exact: true }).inputValue(), 'https://example.test/drive');
  await dialog.getByRole('button', { name: 'Close task detail', exact: true }).click();
  data.manual_actions.push({ id: 'SOLO', product_id: 'qa-fixture', live_status: 'Untested', payload: { title: 'Standalone' }, updated_at: new Date().toISOString(), created_at: new Date().toISOString() });
  emit('manual_actions', 'INSERT', data.manual_actions.at(-1));
  const solo = page.locator('[data-plan-row="SOLO"]');
  await solo.getByRole('button', { name: 'Rename Standalone', exact: true }).click();
  await solo.getByLabel('Task name', { exact: true }).fill('Standalone renamed');
  await solo.getByRole('button', { name: 'Save task name', exact: true }).click();
  await solo.getByRole('button', { name: 'Rename Standalone renamed', exact: true }).waitFor();
  assert.equal(writeCount(), count); assert.equal(data.ads.length, 1);
  await page.setViewportSize({ width: 1440, height: 1000 });
  results.push('Action Plan inline rename/cancel/validation, standalone rename, canonical creative edits and clears, snapshot drafts, local-only saves, remote failure retention, reload and responsive editor');
};
