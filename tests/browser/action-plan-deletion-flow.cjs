const assert = require('node:assert/strict');
module.exports = async function testPlanDeletion({ page, data, control, emit, tab, artifactDir, results }) {
  const base = data.ads[0], action = data.manual_actions[0];
  for (const name of ['Delete local', 'Delete remote', 'Delete stale', 'Delete uncertain', 'Delete virtual', 'Independent variation', 'Locked creative']) {
    const ad = { ...structuredClone(base), id: name, format_name: name, clickup_task_id: name === 'Delete virtual' || name === 'Independent variation' ? null : name.replaceAll(' ', '-'), parent_ad_id: name === 'Independent variation' ? 'Delete local' : null };
    data.ads.push(ad);
    if (name !== 'Delete virtual') data.manual_actions.push({ ...structuredClone(action), id: `action-${name}`, payload: { sourceAdId: name, title: name, _clickupId: ad.clickup_task_id } });
    data.matrix_cells[0].creative_assignments.push(name);
  }
  data.matrix_cells[0].meta = { 'Delete local': { keep: false }, 'Delete local||TOF': {}, 'Independent variation': { keep: true } };
  data.manual_actions.push({ ...structuredClone(action), id: 'standalone-delete', payload: { title: 'Standalone deletion' } });
  data.qa_clickup_creations.push({ id: 'job-locked', product_id: base.product_id, ad_id: 'Locked creative', state: 'uncertain' });
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await tab(page, 'Action Plan');
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'Close creative deletion', exact: true }) });
  const inspect = async (name) => {
    const closeDrawer = page.getByRole('button', { name: 'Close task detail', exact: true });
    if (await closeDrawer.count()) await closeDrawer.click();
    await page.getByRole('button', { name, exact: true }).click();
  };
  const open = async (name) => { await inspect(name); await page.getByRole('button', { name: 'Delete creative', exact: true }).click(); };
  const close = () => dialog.getByRole('button', { name: 'Close creative deletion', exact: true }).click();
  const save = () => dialog.getByRole('button', { name: 'Delete creative', exact: true }).click();
  const pushes = () => control.clickupCalls.filter((c) => c.operation === 'delete-plan-task');
  await inspect('Standalone deletion'); assert.equal(await page.getByRole('button', { name: 'Delete creative', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await inspect('Locked creative'); assert.equal(await page.getByRole('button', { name: 'Delete creative', exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await open('Delete local');
  assert.equal(await dialog.getByRole('checkbox').isChecked(), false);
  await close(); assert.equal(control.deleteCalls?.length || 0, 0);
  await open('Delete local');
  await page.screenshot({ path: `${artifactDir}/action-plan-delete-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-delete-mobile.png`, fullPage: true });
  control.holdDelete = true; await save();
  for (let i = 0; !control.releaseDelete && i < 100; i++) await new Promise((r) => setTimeout(r, 10));
  assert.equal(typeof control.releaseDelete, 'function');
  assert.equal(await dialog.getByRole('button', { name: 'Close creative deletion', exact: true }).isDisabled(), true);
  assert.equal(await dialog.getByRole('checkbox').isDisabled(), true);
  control.releaseDelete();
  await dialog.waitFor({ state: 'detached' });
  await page.locator('[data-plan-row="action-Delete local"]').waitFor({ state: 'detached' });
  assert.ok(data.ads.find((a) => a.id === 'Delete local').deleted_at);
  assert.equal(pushes().length, 0);
  assert.equal(data.manual_actions.some((a) => a.id === 'action-Delete local'), false);
  assert.ok(data.matrix_cells[0].creative_assignments.includes('Independent variation'));
  assert.equal(data.matrix_cells[0].creative_assignments.includes('Delete local'), false);
  assert.deepEqual(data.matrix_cells[0].meta, { 'Independent variation': { keep: true } });
  assert.equal(data.ads.find((a) => a.id === 'Independent variation').deleted_at, undefined);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel('Select Delete local', { exact: true }).count(), 0);
  await page.getByText('Deleted creatives (1)', { exact: true }).click();
  await page.getByRole('button', { name: 'Delete linked ClickUp task for Delete local', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete ClickUp task', exact: true }).click();
  await dialog.waitFor({ state: 'detached' }); assert.equal(pushes().length, 1); assert.equal(control.deleteCalls.length, 1);

  await open('Delete remote'); await dialog.getByRole('checkbox').check(); control.clickupFailure = true;
  await save();
  await dialog.getByRole('alert').filter({ hasText: 'Deleted in QA; ClickUp deletion is not confirmed' }).waitFor();
  assert.ok(data.ads.find((a) => a.id === 'Delete remote').deleted_at);
  const calls = control.deleteCalls.length;
  await close(); control.clickupFailure = false;
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByText('Deleted creatives (2)', { exact: true }).click();
  await page.getByRole('button', { name: 'Delete linked ClickUp task for Delete remote', exact: true }).click();
  await dialog.getByRole('button', { name: 'Delete ClickUp task', exact: true }).click();
  await dialog.waitFor({ state: 'detached' }); assert.equal(control.deleteCalls.length, calls);

  await open('Delete stale'); await dialog.getByRole('checkbox').check();
  const stale = data.ads.find((a) => a.id === 'Delete stale'); stale.updated_at = '2099-01-01T00:00:00Z'; emit('ads', 'UPDATE', stale);
  control.expectedDeleteRejections = 1;
  const remoteBefore = pushes().length;
  await save(); await dialog.getByRole('alert').filter({ hasText: 'Creative changed' }).waitFor();
  assert.equal(await dialog.getByRole('checkbox').isChecked(), true);
  assert.equal(stale.deleted_at, undefined); assert.equal(pushes().length, remoteBefore); await close();

  await open('Delete uncertain'); await dialog.getByRole('checkbox').check(); control.loseDeleteAck = true;
  await save(); await dialog.getByRole('alert').filter({ hasText: 'Deletion could not be verified' }).waitFor();
  assert.equal(pushes().length, remoteBefore);
  await save(); await dialog.waitFor({ state: 'detached' }); assert.equal(pushes().length, remoteBefore + 1);
  await open('Delete virtual'); assert.equal(await dialog.getByRole('checkbox').count(), 0);
  await save(); await dialog.waitFor({ state: 'detached' });
  assert.equal(data.manual_actions.some((a) => a.payload.sourceAdId === 'Delete virtual'), false);
  assert.equal(control.stageCalls?.length || 0, 0);
  assert.equal(control.expectedDeleteRejections, 0);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.getByLabel('Select Delete virtual', { exact: true }).count(), 0);
  await page.getByText('Deleted creatives (4)', { exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-deleted-mobile.png`, fullPage: true });
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  assert.equal(await page.getByText(/Deleted creatives \(/).count(), 0);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Confirmed local/optional remote creative deletion, no-write cancel, busy guards, cascade with independent variations, virtual deletion without promotion, stale/lost-ack protection, remote failure/retry across reload, product isolation, mobile/desktop dialogs');
};
