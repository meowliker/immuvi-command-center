const assert = require('node:assert/strict');

module.exports = async function testDetailCards({ page, context, data, emit, requests, tab, artifactDir, results }) {
  const ad = data.ads[0], action = data.manual_actions[0];
  ad.status = 'Winner';
  ad.meta = { hookType: 'Question', creativeStructure: 'Problem / solution', productionStyle: 'UGC', creativeHypothesis: 'A specific test hypothesis',
    creativeUSP: 'Distinct product benefit', notes: 'First note\nSecond note', _fromInspoId: 'INS-DETAIL',
    _customFields: { 'approved date': '2026-09-16' }, _winningArtifacts: [{ id: 'stale', name: 'Stale cached winner' }] };
  data.inspirations.push({ id: 'INS-DETAIL', product_id: ad.product_id, data: { _clickupDocPageUrl: 'https://example.test/brief' } });
  data.task_video_winners.push({ id: 'winning-1', ad_id: ad.id, drive_file_id: 'winner-file', file_name: 'Verified winner' });
  data.task_video_winners.push({ id: 'foreign-file', ad_id: 'foreign', drive_file_id: 'foreign-file', file_name: 'Other product winner' });
  data.manual_actions.push({ ...structuredClone(action), id: 'COMPLETE', live_status: 'Complete', payload: { title: 'Completed standalone' } });
  await context.route('https://drive.google.com/file/d/*/preview', (route) => route.fulfill({ status: 200, contentType: 'text/html', body: '<p>Fixture preview</p>' }));
  await tab(page, 'Action Plan');
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  const card = page.locator('[data-plan-card="ACTION-1"]');
  await card.waitFor();
  assert.equal(await card.getByRole('link', { name: 'Brief', exact: true }).getAttribute('href'), 'https://example.test/brief');
  await page.getByRole('heading', { name: 'Completed (1)', exact: true }).waitFor();
  assert.deepEqual(await page.locator('[data-plan-card]').evaluateAll((els) => els.map((el) => el.dataset.planCard)), ['ACTION-1', 'COMPLETE']);
  const beforeWidth = (await card.boundingBox()).width;
  await card.getByRole('button', { name: 'Details', exact: true }).click();
  const drawer = page.getByRole('dialog', { name: 'QA creative', exact: true });
  await drawer.getByRole('button', { name: 'Media Buyer', exact: true }).waitFor();
  assert.equal((await card.boundingBox()).width, beforeWidth, 'Opening drawer must not reflow cards');
  await drawer.getByText('Verified winner', { exact: true }).waitFor();
  assert.equal(await drawer.getByText('Stale cached winner', { exact: true }).count(), 0);
  assert.equal(await drawer.getByText('Other product winner', { exact: true }).count(), 0);
  await drawer.getByRole('button', { name: 'Preview Verified winner', exact: true }).click();
  await drawer.locator('iframe[title="Winning file preview"]').waitFor();
  assert.equal(await drawer.locator('iframe').getAttribute('src'), 'https://drive.google.com/file/d/winner-file/preview');
  await drawer.getByRole('button', { name: 'Close preview', exact: true }).click();
  await drawer.getByRole('button', { name: 'Strategist', exact: true }).click();
  for (const text of ['Problem / solution', 'UGC', 'A specific test hypothesis', 'Distinct product benefit']) await drawer.getByText(text, { exact: true }).waitFor();
  assert.equal(await drawer.getByRole('combobox', { name: 'Status', exact: true }).count(), 0);
  ad.meta.creativeHypothesis = 'Revised by another reviewer'; emit('ads', 'UPDATE', ad);
  await drawer.getByText('Revised by another reviewer', { exact: true }).waitFor();
  assert.equal(await drawer.getByRole('button', { name: 'Strategist', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.screenshot({ path: `${artifactDir}/action-plan-strategist-desktop.png`, animations: 'disabled' });
  await drawer.getByRole('button', { name: 'Media Buyer', exact: true }).click();
  await drawer.getByLabel('Winning file URL', { exact: true }).fill('https://drive.google.com/file/d/new-winner/view');
  await drawer.getByLabel('File name', { exact: true }).fill('New winning file');
  await drawer.getByRole('button', { name: 'Save winning file', exact: true }).click();
  await drawer.getByText('Winning file saved.', { exact: true }).waitFor();
  assert.ok(data.task_video_winners.some((file) => file.drive_file_id === 'new-winner'));
  await drawer.getByRole('button', { name: 'Remove New winning file', exact: true }).click();
  await drawer.getByText('Winning file removed.', { exact: true }).waitFor();
  assert.equal(data.task_video_winners.some((file) => file.drive_file_id === 'new-winner'), false);
  await page.screenshot({ path: `${artifactDir}/action-plan-buyer-desktop.png`, animations: 'disabled' });
  for (const width of [320, 390, 768]) {
    await page.setViewportSize({ width, height: 844 });
    const panel = drawer.getByRole('complementary');
    assert.equal(await panel.evaluate((el) => el.scrollWidth <= el.clientWidth), true, `Drawer overflow at ${width}`);
    await page.screenshot({ path: `${artifactDir}/action-plan-buyer-${width}.png`, animations: 'disabled' });
    await drawer.getByRole('button', { name: 'Strategist', exact: true }).click();
    assert.equal(await panel.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
    await drawer.getByRole('button', { name: 'Close task detail', exact: true }).click();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Cards page overflow at ${width}`);
    assert.equal(await card.evaluate((el) => el.scrollWidth <= el.clientWidth), true, `Card overflow at ${width}`);
    await page.screenshot({ path: `${artifactDir}/action-plan-cards-${width}.png`, fullPage: true });
    await card.getByRole('button', { name: 'Details', exact: true }).click();
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  const writesBeforeJump = requests.filter((item) => item.method !== 'GET').length;
  await drawer.getByRole('button', { name: 'Open in Matrix', exact: true }).click();
  await page.getByRole('button', { name: 'Close inspector', exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, '/');
  await page.getByRole('dialog').locator('[data-cell-creative="AD-1"]').waitFor();
  assert.equal(requests.filter((item) => item.method !== 'GET').length, writesBeforeJump, 'Navigation must not write');
  await page.getByRole('button', { name: 'Close inspector', exact: true }).click();
  await tab(page, 'Action Plan');
  await page.getByRole('button', { name: 'QA creative', exact: true }).click();
  data.angles[0].archived_at = new Date().toISOString();
  await drawer.getByRole('button', { name: 'Open in Matrix', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'missing, archived, or ambiguous' }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Close inspector', exact: true }).count(), 0);
  data.angles[0].archived_at = null;
  await tab(page, 'Action Plan');
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await card.getByLabel('Status for QA creative', { exact: true }).selectOption('Testing');
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  assert.equal(ad.status, 'Testing');
  await card.getByLabel('Due date for QA creative', { exact: true }).fill('2026-10-01');
  await page.getByText('Task successfully updated.', { exact: true }).waitFor();
  await page.screenshot({ path: `${artifactDir}/action-plan-cards-desktop.png`, fullPage: true });
  await card.getByRole('button', { name: 'Remove QA creative from Action Plan', exact: true }).click();
  await page.getByText('Task removed from Action Plan. Its creative and ClickUp task were preserved.', { exact: true }).waitFor();
  assert.ok(data.ads.some((item) => item.id === 'AD-1' && !item.deleted_at));
  assert.equal(data.manual_actions.some((item) => item.id === 'ACTION-1'), false);
  results.push('Drawer buyer/strategist parity, live strategy updates, canonical winning files and save/remove/preview, inspiration briefs, same-page exact Matrix navigation and missing-cell guard, full-width cards/completed section, status/due/remove workflows and 320/390/768px layouts');
};
