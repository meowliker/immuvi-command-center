const assert = require('node:assert/strict');
module.exports = async function testPlan({ page, data, control, tab, artifactDir, results }) {
  const original = data.ads[0], action = data.manual_actions[0];
  original.clickup_task_id = 'qa-existing'; action.payload._clickupId = 'qa-existing';
  for (let i = 2; i <= 3; i++) {
    data.ads.push({ ...structuredClone(original), id: `PLAN-AD-${i}`, format_name: `Plan creative ${i}`, persona: i === 3 ? 'Other audience' : 'Busy people', clickup_task_id: `qa-existing-${i}` });
    data.manual_actions.push({ ...structuredClone(action), id: `PLAN-ACTION-${i}`, payload: { adId: `PLAN-AD-${i}`, title: `Plan creative ${i}`, _clickupId: `qa-existing-${i}` } });
  }
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await tab(page, 'Action Plan');
  await page.getByLabel('Select QA creative', { exact: true }).check();
  await page.getByLabel('Select Plan creative 2', { exact: true }).check();
  await page.getByLabel('Show Selected', { exact: true }).check();
  await page.getByLabel('Search Action Plan').fill('QA creative');
  await page.getByText('1 hidden selections excluded', { exact: true }).waitFor();
  await page.getByLabel('Bulk status', { exact: true }).selectOption('Testing');
  control.clickupFailure = true;
  await page.getByRole('button', { name: 'Apply status', exact: true }).click();
  await page.getByRole('region', { name: 'Bulk results', exact: true }).getByText('Saved in QA. ClickUp pending: Synthetic ClickUp outage', { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('[aria-label="Status for QA creative"]')?.value === 'Testing');
  assert.equal(data.ads[1].status, 'Untested', 'Filtered-out selection was mutated');
  assert.equal(await page.getByLabel('Show Selected', { exact: true }).isChecked(), true, 'Pending work must retain selected-only mode');
  control.clickupFailure = false;
  await page.getByRole('button', { name: 'Push selected', exact: true }).click();
  await page.getByText('Pending fields sent to ClickUp.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Reset Action Plan filters', exact: true }).click();
  assert.equal(await page.getByLabel('Select Plan creative 2', { exact: true }).isChecked(), true);
  await page.getByLabel('Show Selected', { exact: true }).check();
  await page.getByLabel('Bulk due date', { exact: true }).fill('2026-10-22');
  await page.getByRole('button', { name: 'Apply date', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Due date for Plan creative 2"]')?.value === '2026-10-22');
  assert.equal(data.ads[0].meta.dueDate, undefined);
  await page.waitForFunction(() => document.querySelector('[aria-label="Show Selected"]')?.checked === false);
  await page.getByLabel('Select Plan creative 2', { exact: true }).check();
  await page.getByLabel('Show Selected', { exact: true }).check();
  await page.getByRole('button', { name: 'Clear dates', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Due date for Plan creative 2"]')?.value === '');
  await page.waitForFunction(() => document.querySelector('[aria-label="Show Selected"]')?.checked === false);
  await page.getByRole('button', { name: 'Filter persona', exact: true }).click();
  await page.getByRole('group', { name: 'Persona options' }).getByRole('checkbox', { name: 'Other audience', exact: true }).check();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('[data-plan-row]').count(), 1);
  await page.getByRole('button', { name: 'Reset Action Plan filters', exact: true }).click();
  await page.getByRole('columnheader').getByRole('button', { name: 'Task name', exact: true }).click();
  assert.equal(await page.locator('[data-plan-row]').first().getAttribute('data-plan-row'), 'PLAN-ACTION-2');

  await page.getByLabel('Select Plan creative 2', { exact: true }).check();
  await page.getByLabel('Select Plan creative 3', { exact: true }).check();
  await page.getByLabel('Show Selected', { exact: true }).check();
  control.holdNextPush = true;
  const before = control.clickupCalls.length;
  await page.getByRole('button', { name: 'Push selected', exact: true }).click();
  for (let i = 0; !control.releasePush && i < 100; i++) await new Promise((resolve) => setTimeout(resolve, 10));
  assert.equal(typeof control.releasePush, 'function');
  assert.equal(await page.getByLabel('Show Selected', { exact: true }).isDisabled(), true);
  await page.getByRole('button', { name: 'Week view', exact: true }).click();
  await page.getByRole('button', { name: 'Stop after current task', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Trends view', exact: true }).click();
  await page.getByRole('button', { name: 'Variations view', exact: true }).click();
  await page.getByRole('button', { name: 'Stop after current task', exact: true }).click();
  control.releasePush(); control.releasePush = null;
  await page.getByText('Not sent.', { exact: true }).waitFor();
  assert.equal(control.clickupCalls.length - before, 1, 'Stop sent an additional task');
  await page.getByRole('button', { name: 'Table view', exact: true }).click();
  assert.equal(await page.getByLabel('Select Plan creative 3', { exact: true }).isChecked(), true);
  assert.equal(await page.getByLabel('Show Selected', { exact: true }).isChecked(), true);
  await page.getByRole('button', { name: 'Clear selection', exact: true }).click();
  await page.getByLabel('Select all visible tasks', { exact: true }).check();
  await page.screenshot({ path: `${artifactDir}/action-plan-table-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-table-mobile.png`, fullPage: true });
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await page.getByRole('button', { name: 'Details', exact: true }).first().click();
  await page.getByRole('button', { name: 'Close task detail' }).click();
  await page.getByRole('button', { name: 'Table view', exact: true }).click();
  await page.getByRole('button', { name: 'Remove selected from plan', exact: true }).click();
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  assert.equal(data.ads.length, 3); assert.equal(data.manual_actions.length, 0);
  assert.equal(control.clickupCalls.some((c) => /delete/i.test(c.operation)), false);
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  results.push('Action Plan table/filter/sort, hidden selection exclusion, bulk status/dates, partial ClickUp failures, retry, stop, removal preservation and desktop/mobile layouts');
};
