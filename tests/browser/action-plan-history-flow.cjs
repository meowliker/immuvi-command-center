const assert = require('node:assert/strict');
module.exports = async function testPlanHistory({ page, data, control, emit, tab, artifactDir, results }) {
  const stamp = '2026-09-16T12:00:00.000Z';
  data.ads[0].clickup_task_id = 'history-task';
  Object.assign(data.manual_actions[0].payload, { _origin: 'adopted', _adoptedAt: Date.parse(stamp) - 1000, _pushedAt: Date.parse(stamp) - 500,
    _history: Array.from({ length: 50 }, (_, i) => ({ ts: Date.parse(stamp) - 10_000 - i, type: 'tag_added', detail: `Legacy ${i}`, by: 'Legacy actor' })) });
  data.manual_actions[0].payload._history[0].detail = '<img src=x onerror=alert(1)>';
  data.ads.push({ ...structuredClone(data.ads[0]), id: 'OTHER-AD', format_name: 'Other task', clickup_task_id: null });
  data.manual_actions.push({ ...structuredClone(data.manual_actions[0]), id: 'OTHER-ACTION', payload: { adId: 'OTHER-AD', title: 'Other task' } });
  const event = (id, patch = {}) => ({ id, product_id: 'qa-fixture', action_id: 'ACTION-1', clickup_task_id: null, created_at: stamp, event_type: 'status_changed', field_name: 'status', old_value: 'Testing', new_value: 'Winner', actor: 'Reviewer', source: 'qa-next', ...patch });
  for (let i = 0; i < 85; i++) data.activity_events.push(event(`target-${String(i).padStart(3, '0')}`));
  for (let i = 0; i < 120; i++) data.activity_events.push(event(`other-${String(i).padStart(3, '0')}`, { action_id: 'OTHER-ACTION', created_at: '2026-09-17T12:00:00.000Z' }));
  data.activity_events.push(event('task-only', { action_id: null, clickup_task_id: 'history-task' }), event('ad-only', { action_id: null, metadata: { ad_id: 'AD-1' } }), event('foreign', { product_id: 'qa-second' }));
  await tab(page, 'Action Plan');
  await page.getByRole('button', { name: 'QA creative', exact: true }).click();
  const history = page.getByRole('region', { name: 'Task history', exact: true });
  const recorded = () => history.locator('[data-history-id^="event:"]');
  await history.getByText('40 recorded events loaded', { exact: true }).waitFor();
  assert.equal(await recorded().count(), 40); assert.equal(await history.locator('[data-history-id^="legacy:"]').count(), 50);
  assert.equal(await history.locator('img').count(), 0);
  assert.equal(await history.locator('[data-history-id="milestone:adopted"]').count(), 1);
  assert.equal(await history.locator('[data-history-id="event:other-119"]').count(), 0);
  control.historyFailure = true;
  await history.getByRole('button', { name: 'Load older events', exact: true }).click();
  await history.getByRole('alert').waitFor(); assert.equal(await recorded().count(), 40);
  control.historyFailure = false;
  await history.getByRole('button', { name: 'Retry history', exact: true }).click();
  await history.getByText('80 recorded events loaded', { exact: true }).waitFor();
  await history.getByRole('button', { name: 'Load older events', exact: true }).click();
  await history.getByText('87 recorded events loaded - all available events loaded', { exact: true }).waitFor();
  const ids = await recorded().evaluateAll((els) => els.map((el) => el.dataset.historyId));
  assert.equal(new Set(ids).size, 87); assert.ok(ids.includes('event:ad-only')); assert.ok(ids.includes('event:task-only'));
  assert.equal(await history.getByRole('button', { name: 'Load older events', exact: true }).count(), 0);
  const next = event('newest', { created_at: '2026-09-18T12:00:00.000Z' }); data.activity_events.push(next); emit('activity_events', 'INSERT', next);
  await history.getByText('88 recorded events loaded - all available events loaded', { exact: true }).waitFor();
  await page.screenshot({ path: `${artifactDir}/action-plan-history-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await history.scrollIntoViewIfNeeded();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await history.screenshot({ path: `${artifactDir}/action-plan-history-mobile.png` });

  control.holdHistory = true;
  const held = new Promise((resolve) => { control.historyHeld = resolve; });
  await history.getByRole('button', { name: 'Refresh history', exact: true }).click(); await held;
  await page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await page.getByRole('button', { name: 'Other task', exact: true }).click();
  control.releaseHistory();
  await history.getByText('40 recorded events loaded', { exact: true }).waitFor();
  assert.equal(await history.locator('[data-history-id^="event:target"]').count(), 0);
  assert.equal(await history.locator('[data-history-id^="legacy:"]').count(), 0);
  await page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  const product = page.getByRole('region', { name: 'Product history', exact: true });
  await product.getByText('40 recorded events loaded', { exact: true }).waitFor();
  await product.getByRole('button', { name: 'Load older events', exact: true }).click();
  await product.getByText('80 recorded events loaded', { exact: true }).waitFor();
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await product.getByText('1 recorded events loaded - all available events loaded', { exact: true }).waitFor();
  assert.equal(await product.locator('[data-history-id="event:foreign"]').count(), 1);
  assert.equal(await product.locator('[data-history-id^="event:target"]').count(), 0);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Task/product keyset history beyond global 40-event limit, all retained legacy entries, safe text, milestones, failed-page preservation/retry, tied timestamps, realtime refresh, stale task cancellation, product isolation and responsive scrolling; no writes');
};
