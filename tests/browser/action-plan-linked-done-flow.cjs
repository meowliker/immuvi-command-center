const assert = require('node:assert/strict');
const { choosePlanDate } = require('./plan-date-helpers.cjs');
module.exports = async function testPlanLinkedDone({ page, data, control, emit, tab, artifactDir, results }) {
  const now = new Date(2026, 8, 16, 12).getTime(), day = 86_400_000;
  await page.clock.setFixedTime(now);
  const ad = data.ads[0];
  Object.assign(ad, { status: 'Ready to Launch', clickup_task_id: 'source-task', created_at: new Date(now - 40 * day).toISOString(), last_status_change_at: now - 20 * day });
  control.linkedDone = { [ad.id]: { doneAt: now - day } };
  await tab(page, 'Action Plan');
  const row = page.locator('[data-plan-row="ACTION-1"]'), age = row.locator('[data-plan-age]');
  const refresh = page.getByRole('button', { name: 'Refresh production completion dates', exact: true });
  const refreshRead = async () => {
    const completed = page.waitForResponse((response) => response.url().endsWith('/api/clickup/qa') && response.request().postDataJSON().operation === 'plan-linked-done');
    await refresh.click(); await completed;
    await page.waitForFunction(() => !document.querySelector('[aria-label="Refresh production completion dates"]').disabled);
  };
  await page.getByText('Using fallback timestamps. Enter a ClickUp key in the QA connection controls.', { exact: true }).waitFor();
  assert.equal(await age.innerText(), '! 20d');
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  const calls = () => control.clickupCalls.filter((call) => call.operation === 'plan-linked-done').length;
  await refreshRead(); await page.waitForFunction(() => document.querySelector('[data-plan-age]')?.textContent === '1d');
  assert.equal(calls(), 1);
  await page.getByLabel('Select QA creative', { exact: true }).check();
  await choosePlanDate(page, 'yesterday'); assert.equal(await row.count(), 1);
  await choosePlanDate(page, 'today'); await page.getByText('1 hidden selections excluded', { exact: true }).waitFor();
  assert.equal(await row.count(), 0);
  control.linkedDone[ad.id].doneAt = now;
  await refreshRead(); await row.waitFor(); assert.equal(await age.innerText(), 'just now');
  assert.equal(await page.getByLabel('Select QA creative', { exact: true }).isChecked(), true);
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await page.getByRole('button', { name: 'Table view', exact: true }).click();
  assert.equal(calls(), 2);
  await page.screenshot({ path: `${artifactDir}/action-plan-linked-desktop.png`, fullPage: true });

  control.linkedDone[ad.id] = { doneAt: now, version: 'stale' };
  await refreshRead(); await page.getByText('Using fallback timestamps. Task changed. Refresh completion dates.', { exact: true }).waitFor();
  assert.equal(await row.count(), 0);
  control.linkedDone[ad.id] = { doneAt: null };
  await choosePlanDate(page, 'all'); await refreshRead();
  assert.equal(await page.getByText('Using fallback timestamps. Task changed. Refresh completion dates.', { exact: true }).count(), 0);
  assert.equal(await age.innerText(), '! 20d');
  const negativeCalls = calls();
  await page.clock.setFixedTime(now + 60_000); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await page.getByRole('button', { name: 'Table view', exact: true }).click(); assert.equal(calls(), negativeCalls);
  control.linkedDone[ad.id] = { doneAt: now - 2 * day };
  await page.clock.setFixedTime(now + 6 * 60_000); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.waitForFunction(() => document.querySelector('[data-plan-age]')?.textContent === '2d');
  assert.equal(calls(), negativeCalls + 1);
  control.linkedDone[ad.id] = { doneAt: now - 3 * day };
  ad.updated_at = new Date(now).toISOString(); emit('ads', 'UPDATE', ad);
  await page.waitForFunction(() => document.querySelector('[data-plan-age]')?.textContent === '! 3d');
  assert.equal(calls(), negativeCalls + 2);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-linked-mobile.png`, fullPage: true });

  const linkedHeld = new Promise((resolve) => { control.linkedHeld = resolve; });
  control.holdNextLinked = true; await refresh.click();
  await page.getByText('Loading production completion dates...', { exact: true }).waitFor();
  await linkedHeld;
  assert.equal(typeof control.releaseLinked, 'function');
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  control.releaseLinked();
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  assert.equal(await refresh.count(), 0); assert.equal(await page.locator('[data-plan-age]').count(), 0);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Linked production dates: missing key fallback, refresh, shared date/age projection, retained selection, stale response rejection, negative caching, TTL, realtime invalidation and product-change cancellation; no writes');
};
