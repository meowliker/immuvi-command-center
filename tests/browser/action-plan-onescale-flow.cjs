const assert = require('node:assert/strict');
module.exports = async function testPlanOneScale({ page, data, control, tab, artifactDir, results }) {
  const base = data.ads[0], first = data.manual_actions[0];
  for (const id of ['launch-ready', 'launch-hidden', 'launch-virtual']) {
    data.ads.push({ ...structuredClone(base), id, format_name: id, status: 'Ready to Launch', clickup_task_id: `task-${id}`, meta: { _clickupId: `task-${id}` } });
    if (id !== 'launch-virtual') data.manual_actions.push({ ...structuredClone(first), id: `action-${id}`, live_status: 'Ready to Launch', payload: { sourceAdId: id, title: id, _clickupId: `task-${id}` } });
  }
  await tab(page, 'Action Plan');
  const review = page.getByRole('button', { name: 'Review OneScale launch', exact: true });
  const dialog = page.getByRole('dialog', { name: 'OneScale launch review', exact: true });
  const verify = () => dialog.getByRole('button', { name: 'Verify selected tasks', exact: true }).click();
  const close = () => dialog.getByRole('button', { name: 'Close OneScale review', exact: true }).click();
  const calls = () => control.clickupCalls.filter((c) => c.operation === 'review-onescale');
  assert.equal(await review.isDisabled(), true);
  await page.getByRole('checkbox', { name: 'Select QA creative', exact: true }).check();
  assert.equal(await review.isDisabled(), true);
  await page.getByRole('checkbox', { name: 'Select launch-hidden', exact: true }).check();
  await page.getByLabel('Search Action Plan', { exact: true }).fill('launch-ready');
  assert.equal(await review.isDisabled(), true);
  await page.getByRole('checkbox', { name: 'Select launch-ready', exact: true }).check();
  await review.click(); assert.equal(calls().length, 0);
  assert.equal(await dialog.getByText('launch-hidden', { exact: true }).count(), 0);
  assert.equal(await dialog.getByRole('button', { name: 'Launch in OneScale', exact: true }).isDisabled(), true);
  await verify(); await dialog.getByRole('alert').filter({ hasText: 'Enter a ClickUp key' }).waitFor();
  assert.equal(calls().length, 0); await close();
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await review.click(); control.holdOneScale = true; await verify();
  for (let i = 0; !control.releaseOneScale && i < 100; i++) await new Promise((r) => setTimeout(r, 10));
  assert.equal(typeof control.releaseOneScale, 'function');
  assert.equal(await dialog.getByRole('button', { name: 'Close OneScale review' }).isDisabled(), true);
  control.releaseOneScale(); await dialog.getByText(/QA and ClickUp readiness verified/).waitFor();
  assert.equal(calls().length, 1); assert.equal(calls()[0].targets.length, 1); assert.equal(calls()[0].targets[0].adId, 'launch-ready');
  await page.screenshot({ path: `${artifactDir}/action-plan-onescale-desktop.png` });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-onescale-mobile.png` });
  await close(); await page.setViewportSize({ width: 1440, height: 1000 });
  await review.click(); control.oneScaleError = 'Task changed. Reopen launch review.'; await verify();
  await dialog.getByRole('alert').filter({ hasText: 'Task changed' }).waitFor();
  assert.equal(await dialog.getByText(/readiness verified/).count(), 0); control.oneScaleError = ''; await close();
  await review.click(); control.oneScaleUnsafe = true; await verify();
  await dialog.getByRole('alert').filter({ hasText: 'response could not be verified' }).waitFor();
  assert.equal(await dialog.getByRole('button', { name: 'Launch in OneScale', exact: true }).isDisabled(), true);
  control.oneScaleUnsafe = false; await close();
  await page.getByLabel('Search Action Plan', { exact: true }).fill('launch-virtual');
  await page.getByRole('checkbox', { name: 'Select launch-virtual', exact: true }).check();
  await review.click(); await verify(); await dialog.getByText(/readiness verified/).waitFor();
  assert.equal(calls().at(-1).targets[0].actionId, null); await close();
  assert.equal(data.manual_actions.some((a) => a.payload.sourceAdId === 'launch-virtual'), false);
  assert.equal(data.ads.find((a) => a.id === 'launch-ready').status, 'Ready to Launch');
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  assert.equal(await dialog.count(), 0); assert.equal(await review.isDisabled(), true);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Read-only OneScale readiness: hidden/non-ready selections excluded, no-key/failure/unsafe response handling, busy guards, virtual rows without staging, product isolation, disabled launch and responsive dialog; no writes or external handoff');
};
