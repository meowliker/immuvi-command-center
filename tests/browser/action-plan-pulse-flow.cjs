const assert = require('node:assert/strict');
const { openDateMenu, dateTrigger } = require('./plan-date-helpers.cjs');
module.exports = async function testPlanPulse({ page, data, emit, tab, artifactDir, results }) {
  const now = new Date(2026, 8, 16, 12).getTime();
  await page.clock.setFixedTime(now);
  const date = (day) => new Date(2026, 8, day, 12).getTime();
  const ad = data.ads[0], action = data.manual_actions[0];
  Object.assign(ad, { status: 'Testing', created_at: new Date(date(1)).toISOString(), last_status_change_at: date(15) });
  for (const [id, status, changed] of [['win', 'Mild Winner', 16], ['prod', 'In Production', 16], ['kill', 'Killed', 15], ['old', 'Live', 10]]) {
    data.ads.push({ ...structuredClone(ad), id, format_name: id, status, last_status_change_at: date(changed) });
    data.manual_actions.push({ ...structuredClone(action), id: `action-${id}`, payload: { adId: id, title: id } });
  }
  await tab(page, 'Action Plan');
  const pulse = page.getByRole('region', { name: 'Action Plan pulse', exact: true });
  const tile = (key) => pulse.locator(`[data-pulse-key="${key}"]`);
  const count = (key) => tile(key).locator('[data-pulse-count]').innerText();
  const ids = () => page.locator('[data-plan-row]').evaluateAll((els) => els.map((el) => el.dataset.planRow));
  assert.equal(await count('today:decisions'), '1'); assert.equal(await count('week:killed'), '1');
  assert.equal(await count('today:launched'), '0');
  await page.getByLabel('Select old', { exact: true }).check();
  await tile('today:launched').click(); assert.deepEqual(await ids(), []);
  await page.getByText('1 hidden selections excluded', { exact: true }).waitFor();
  await tile('week:winners').click(); assert.deepEqual((await ids()).sort(), ['ACTION-1', 'action-win']);
  assert.equal(await dateTrigger(page).getAttribute('data-preset'), 'week');
  await page.getByRole('button', { name: 'Remove Today: Launched filter', exact: true }).click();
  assert.deepEqual(await ids(), ['action-win']);
  await tile('week:winners').focus(); await page.keyboard.press('Space');
  assert.equal(await page.locator('[data-plan-row]').count(), 5);
  assert.equal(await tile('week:winners').getAttribute('aria-pressed'), 'false');
  await tile('today:created').click(); assert.deepEqual(await ids(), []);
  const dateOptions = await openDateMenu(page);
  assert.equal(await dateOptions.getByRole('button', { name: 'Created', exact: true }).getAttribute('aria-pressed'), 'true');
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Clear all filters', exact: true }).click();

  await pulse.getByRole('button', { name: 'Pulse date range', exact: true }).click();
  const dialog = page.getByRole('group', { name: 'Pulse date options', exact: true });
  await dialog.getByLabel('Start date', { exact: true }).fill('2026-09-10');
  await dialog.getByLabel('End date', { exact: true }).fill('2026-09-15');
  await dialog.getByRole('button', { name: 'Apply date range', exact: true }).click();
  assert.equal(await count('week:launched'), '2');
  await tile('today:launched').click(); assert.deepEqual((await ids()).sort(), ['ACTION-1', 'action-old']);
  assert.equal(await dateTrigger(page).getAttribute('data-preset'), 'custom');
  await page.getByLabel('Search Action Plan').fill('QA creative'); assert.deepEqual(await ids(), ['ACTION-1']);
  assert.equal(await count('week:launched'), '2');
  await page.getByRole('button', { name: 'Remove Search: QA creative filter', exact: true }).click();
  await page.getByRole('button', { name: 'Filter adType', exact: true }).click();
  await page.getByRole('group', { name: 'Type options' }).getByRole('checkbox', { name: 'Video', exact: true }).check();
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: 'Remove Type: Video filter', exact: true }).click();
  await tile('today:launched').click();
  assert.equal(await dateTrigger(page).getAttribute('data-preset'), 'custom');
  assert.equal(await page.locator('[data-plan-row]').count(), 3);
  await page.screenshot({ path: `${artifactDir}/action-plan-pulse-desktop.png`, fullPage: true });
  await pulse.getByRole('button', { name: 'Pulse date range', exact: true }).click();
  await dialog.getByLabel('Start date', { exact: true }).fill('2026-09-16');
  await dialog.getByRole('button', { name: 'Apply date range', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(await count('week:launched'), '2');
  await dialog.getByRole('button', { name: 'Cancel date range', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-pulse-mobile.png`, fullPage: true });
  await pulse.getByRole('button', { name: 'Pulse date range', exact: true }).click();
  await dialog.getByRole('button', { name: 'Reset pulse date range', exact: true }).click();
  assert.equal(await dateTrigger(page).getAttribute('data-preset'), 'all');
  assert.equal(await count('week:launched'), '1');
  assert.equal(await page.getByLabel('Select old', { exact: true }).isChecked(), true);
  ad.last_status_change_at = now; emit('ads', 'UPDATE', ad);
  await page.waitForFunction(() => document.querySelector('[data-pulse-key="today:launched"] [data-pulse-count]')?.textContent === '1');
  await tile('today:launched').click(); assert.deepEqual(await ids(), ['ACTION-1']);
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  assert.equal(await tile('today:launched').getAttribute('aria-pressed'), 'true');
  await page.getByRole('button', { name: 'Trends view', exact: true }).click(); assert.equal(await pulse.count(), 0);
  await page.getByRole('button', { name: 'Table view', exact: true }).click();
  assert.equal(await tile('today:launched').getAttribute('aria-pressed'), 'true');
  await page.clock.setFixedTime(new Date(2026, 8, 17, 12)); await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.waitForFunction(() => document.querySelector('[data-pulse-key="today:launched"] [data-pulse-count]')?.textContent === '0');
  assert.deepEqual(await ids(), []);
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  assert.equal(await count('week:launched'), '0'); assert.equal(await tile('today:launched').getAttribute('aria-pressed'), 'false');
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Pulse counters/deltas, union and zero-count filtering, keyboard toggles, chips, custom period validation/reset, search/type composition, retained hidden selection, realtime/clock updates, layout/product isolation and responsive rendering');
};
