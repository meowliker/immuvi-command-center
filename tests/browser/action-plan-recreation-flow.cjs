const assert = require('node:assert/strict');
module.exports = async function testPlanRecreation({ page, data, control, tab, artifactDir, results }) {
  const base = data.ads[0], first = data.manual_actions[0];
  control.repairOutcomes = { 'repair-new': 'replacement', 'repair-marker': 'marker', 'repair-error': 'error', 'repair-uncertain': 'uncertain' };
  for (const id of ['repair-live', 'repair-new', 'repair-marker', 'repair-error', 'repair-stale', 'repair-uncertain', 'repair-virtual', 'repair-locked']) {
    data.ads.push({ ...structuredClone(base), id, format_name: id, clickup_task_id: `old-${id}`, meta: { _clickupId: `old-${id}`, _clickupTaskDeleted: true, notes: 'Preserved brief' } });
    if (id !== 'repair-virtual') data.manual_actions.push({ ...structuredClone(first), id: `action-${id}`, payload: { sourceAdId: id, title: id, _clickupId: `old-${id}`, _clickupTaskDeleted: true, description: 'Preserved action brief' } });
  }
  data.qa_clickup_creations.push({ id: 'locked', product_id: base.product_id, ad_id: 'repair-locked', state: 'uncertain' });
  await page.evaluate(() => sessionStorage.setItem('immuvi:qa:entgcnlfsnysnwyadzzp:clickup:11111111-1111-4111-8111-111111111111', 'synthetic-clickup-key'));
  await tab(page, 'Action Plan');
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('button', { name: 'Close ClickUp repair', exact: true }) });
  const inspect = (name) => page.getByRole('button', { name, exact: true }).click();
  const closeInspector = () => page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  const open = async (name) => { await inspect(name); await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).click(); };
  const save = () => dialog.getByRole('button', { name: 'Repair or recreate', exact: true }).click();
  const close = () => dialog.getByRole('button', { name: 'Close ClickUp repair', exact: true }).click();
  const calls = () => control.clickupCalls.filter((c) => c.operation === 'repair-plan-task');
  await inspect('QA creative'); assert.equal(await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).count(), 0); await closeInspector();
  await inspect('repair-locked'); assert.equal(await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).count(), 0); await closeInspector();
  await open('repair-live'); await close(); assert.equal(calls().length, 0); await closeInspector();
  await open('repair-live');
  await page.screenshot({ path: `${artifactDir}/action-plan-repair-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-repair-mobile.png`, fullPage: true });
  control.holdRepair = true; await save();
  for (let i = 0; !control.releaseRepair && i < 100; i++) await new Promise((r) => setTimeout(r, 10));
  assert.equal(typeof control.releaseRepair, 'function');
  assert.equal(await dialog.getByRole('button', { name: 'Close ClickUp repair', exact: true }).isDisabled(), true);
  control.releaseRepair(); await dialog.waitFor({ state: 'detached' });
  await page.getByRole('status').filter({ hasText: 'Verified and restored ClickUp link old-repair-live' }).waitFor();
  assert.equal(control.repairPosts || 0, 0); await closeInspector(); await page.setViewportSize({ width: 1440, height: 1000 });

  await open('repair-error'); await save();
  await dialog.getByRole('alert').filter({ hasText: 'verification failed' }).waitFor();
  assert.equal(data.ads.find((a) => a.id === 'repair-error').clickup_task_id, 'old-repair-error');
  assert.equal(control.repairPosts || 0, 0); await close(); await closeInspector();
  await open('repair-stale'); data.ads.find((a) => a.id === 'repair-stale').updated_at = '2099-01-01T00:00:00Z';
  await save(); await dialog.getByRole('alert').filter({ hasText: 'Task changed' }).waitFor(); await close(); await closeInspector();
  await open('repair-marker'); await save(); await dialog.waitFor({ state: 'detached' });
  assert.equal(control.repairPosts || 0, 0); assert.equal(data.ads.find((a) => a.id === 'repair-marker').clickup_task_id, 'repaired-repair-marker'); await closeInspector();
  await open('repair-new'); await save(); await dialog.waitFor({ state: 'detached' });
  assert.equal(control.repairPosts, 1); assert.equal(data.ads.find((a) => a.id === 'repair-new').meta.notes, 'Preserved brief');
  assert.equal(data.manual_actions.find((a) => a.id === 'action-repair-new').payload.description, 'Preserved action brief'); await closeInspector();
  await open('repair-virtual'); await save(); await dialog.waitFor({ state: 'detached' });
  await page.locator('[data-plan-row="repair-repair-virtual"]').waitFor();
  assert.equal(calls().at(-1).actionId, null); assert.equal(calls().at(-1).actionVersion, null);
  assert.equal(await page.getByRole('button', { name: 'Close task detail', exact: true }).count(), 1); await closeInspector();

  await open('repair-uncertain'); await save();
  await dialog.getByRole('alert').filter({ hasText: 'may have created' }).waitFor(); assert.equal(control.repairPosts, 2);
  await close(); await page.reload({ waitUntil: 'networkidle' });
  await page.getByRole('button', { name: 'Recover ClickUp link for repair-uncertain', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-plan-row="action-repair-uncertain"] a')?.textContent.includes('ClickUp'));
  assert.equal(control.creationPosts || 0, 0); assert.equal(control.repairPosts, 2);
  await page.getByRole('button', { name: 'Cards view', exact: true }).click();
  await page.locator('article').filter({ has: page.getByRole('checkbox', { name: 'Select repair-live', exact: true }) }).getByRole('button', { name: 'Details', exact: true }).click();
  await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).click(); await close(); await closeInspector();
  await page.getByRole('button', { name: 'Pipeline view', exact: true }).click();
  await page.getByRole('button', { name: 'Open repair-new', exact: true }).click();
  await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).click(); await close();
  await closeInspector();
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: 'Repair ClickUp link', exact: true }).count(), 0);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('ClickUp repair confirmation/cancel, restored and marked links, guarded recreation, failed lookup/stale preservation, virtual promotion, busy lock, uncertain-create recovery after reload, product isolation, cards/pipeline and responsive dialogs');
};
