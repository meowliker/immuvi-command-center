const assert = require('node:assert/strict');
const { choosePlanDate, setPlanDateBasis, openDateMenu, dateMenu } = require('./plan-date-helpers.cjs');
module.exports = async function testPlanTrends({ page, data, emit, tab, artifactDir, results }) {
  await page.clock.setFixedTime(new Date(2026, 8, 16, 12));
  const dates = await page.evaluate(() => Object.fromEntries(['2026-08-17', '2026-08-18', '2026-09-15', '2026-09-16'].map((date) => [date, new Date(`${date}T12:00:00`).toISOString()])));
  const ad = data.ads[0], action = data.manual_actions[0];
  ad.status = 'Testing'; ad.created_at = dates['2026-08-18']; ad.last_status_change_at = Date.parse(dates['2026-09-15']);
  for (const [index, status, created, changed] of [[2, 'Winner', '2026-09-16', '2026-09-16'], [3, 'Loser', '2026-08-17', '2026-08-17'], [4, 'In Production', '2026-09-16', null]]) {
    data.ads.push({ ...structuredClone(ad), id: `TREND-AD-${index}`, format_name: `Trend task ${index}`, status, created_at: dates[created], last_status_change_at: changed ? Date.parse(dates[changed]) : null });
    data.manual_actions.push({ ...structuredClone(action), id: `TREND-ACTION-${index}`, payload: { adId: `TREND-AD-${index}`, title: `Trend task ${index}` } });
  }
  await tab(page, 'Action Plan');
  await page.getByLabel('Select Trend task 3', { exact: true }).check();
  const preset = page.getByLabel('Action Plan date range', { exact: true });
  await choosePlanDate(page, 'today');
  // In Production uses its creation date when no status/approval date exists.
  assert.deepEqual(await page.locator('[data-plan-row]').evaluateAll((els) => els.map((el) => el.dataset.planRow)), ['TREND-ACTION-2', 'TREND-ACTION-4']);
  await page.getByText('1 hidden selections excluded', { exact: true }).waitFor();
  await setPlanDateBasis(page, 'Created');
  assert.equal(await page.locator('[data-plan-row]').count(), 2);
  await setPlanDateBasis(page, 'Activity');
  await choosePlanDate(page, 'yesterday');
  assert.equal(await page.locator('[data-plan-row]').getAttribute('data-plan-row'), 'ACTION-1');
  await choosePlanDate(page, 'custom');
  const dialog = dateMenu(page);
  await dialog.getByLabel('Start date', { exact: true }).fill('2026-09-16');
  await dialog.getByLabel('End date', { exact: true }).fill('2026-09-15');
  await dialog.getByRole('button', { name: 'Apply date range', exact: true }).click();
  await dialog.getByRole('alert').waitFor();
  assert.equal(await page.locator('[data-plan-row]').count(), 1);
  await dialog.getByLabel('Start date', { exact: true }).fill('2026-09-15');
  await dialog.getByLabel('End date', { exact: true }).fill('2026-09-16');
  await page.screenshot({ path: `${artifactDir}/action-plan-date-desktop.png` });
  await dialog.getByRole('button', { name: 'Apply date range', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await page.locator('[data-plan-row]').count(), 3);
  await page.setViewportSize({ width: 390, height: 844 });
  await openDateMenu(page);
  await dialog.getByLabel('Start date', { exact: true }).fill('2026-08-01');
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-date-mobile.png` });
  await dialog.getByRole('button', { name: 'Cancel date range', exact: true }).click();
  assert.equal(await page.locator('[data-plan-row]').count(), 3);
  await page.getByLabel('Search Action Plan').fill('QA creative');
  await page.getByRole('button', { name: 'QA creative', exact: true }).click();
  await page.getByRole('button', { name: 'Close task detail', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Close task detail', exact: true }).click();
  await page.getByRole('button', { name: 'Trends view', exact: true }).click();
  const trends = page.getByRole('region', { name: 'Action Plan trends', exact: true });
  assert.equal(await page.getByLabel('Search Action Plan').count(), 0);
  assert.equal(await page.getByLabel('Bulk status', { exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: 'Close task detail', exact: true }).count(), 0);
  assert.equal(await trends.locator('[data-trend-total="created"]').innerText(), '3');
  assert.equal(await trends.locator('[data-trend-total="launched"]').innerText(), '1');
  assert.equal(await trends.locator('[data-trend-total="decided"]').innerText(), '1');
  assert.equal(await trends.locator('[data-trend-win-rate]').innerText(), '50%');
  assert.equal(await trends.locator('[data-trend-date]').count(), 90);
  assert.equal(await trends.locator('[data-trend="created"] [data-count="2"]').evaluate((el) => el.getBoundingClientRect().height > 0), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-trends-mobile.png`, fullPage: true });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await trends.getByText('Daily totals', { exact: true }).click();
  assert.equal(await trends.locator('tbody tr').count(), 30);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await trends.getByText('Daily totals', { exact: true }).click();
  await page.screenshot({ path: `${artifactDir}/action-plan-trends-desktop.png`, fullPage: true });
  const changed = data.ads[3]; changed.status = 'Live'; changed.last_status_change_at = Date.parse(dates['2026-09-16']);
  emit('ads', 'UPDATE', changed);
  await page.waitForFunction(() => document.querySelector('[data-trend-total="launched"]')?.textContent === '2');
  await page.getByRole('button', { name: 'Table view', exact: true }).click();
  assert.equal(await preset.getAttribute('data-preset'), 'custom');
  assert.equal(await page.getByLabel('Search Action Plan').inputValue(), 'QA creative');
  await page.getByRole('button', { name: 'Reset Action Plan filters', exact: true }).click();
  assert.equal(await preset.getAttribute('data-preset'), 'all');
  assert.equal(await page.getByLabel('Select Trend task 3', { exact: true }).isChecked(), true);
  await choosePlanDate(page, 'today');
  assert.equal(await page.locator('[data-plan-row]').count(), 2);
  await page.clock.setFixedTime(new Date(2026, 8, 17, 12));
  await page.evaluate(() => window.dispatchEvent(new Event('focus')));
  await page.getByText('No Action Plan tasks match these filters.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Trends view', exact: true }).click();
  assert.equal(await trends.locator('[data-trend="created"] [data-trend-date]').last().getAttribute('data-trend-date'), '2026-09-17');
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.getByRole('button', { name: 'Trends view', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('[data-trend-total="created"]')?.textContent === '0');
  assert.equal(await trends.locator('[data-trend-win-rate]').innerText(), '0%');
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Action Plan date presets/basis, validated custom apply/cancel, hidden selection safety, all-product trends/win rate/daily totals, realtime updates, clock rollover, product isolation and responsive charts');
};
