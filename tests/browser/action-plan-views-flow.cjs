const assert = require('node:assert/strict');
const resizeColumn = require('./plan-column-resize.cjs');
const { beginDrag } = require('./plan-column-order.cjs');
module.exports = async function testPlanViews({ page, context, data, emit, control, tab, artifactDir, results }) {
  data.ads[0].meta._customFields = { score: '0' };
  await tab(page, 'Action Plan');
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.getByLabel('Show Task name', { exact: true }).isDisabled(), true);
  await dialog.getByLabel('Show Reviewer', { exact: true }).uncheck();
  await dialog.getByLabel('Show score', { exact: true }).check();
  assert.equal(await dialog.getByRole('spinbutton').count(), 0);
  const order = () => dialog.locator('[data-column-option]').evaluateAll(rows => rows.map(row => row.dataset.columnOption));
  const initialOrder = await order();
  await beginDrag(page, dialog, 'Task name', 'Funnel', 'after');
  await page.screenshot({ path: `${artifactDir}/column-drop-highlight-desktop.png` });
  await page.mouse.up();
  assert.deepEqual((await order()).slice(0, 5), ['cb', 'source', 'origin', 'funnel', 'title']);
  await beginDrag(page, dialog, 'Task name', 'Origin');
  await page.mouse.up();
  assert.deepEqual(await order(), initialOrder);
  await beginDrag(page, dialog, 'Task name', 'Funnel', 'after');
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.deepEqual(await order(), initialOrder, 'Escape cancels without closing the dialog');
  assert.equal(await dialog.locator('[data-drop]').count(), 0);
  await beginDrag(page, dialog, 'Task name', 'Funnel', 'after');
  await page.mouse.move(2, 2); await page.mouse.up();
  assert.deepEqual(await order(), initialOrder, 'Dropping outside cancels');
  const taskGrip = dialog.getByRole('button', { name: 'Drag Task name to reorder', exact: true });
  await taskGrip.press('ArrowDown'); await taskGrip.press('ArrowUp');
  assert.deepEqual(await order(), initialOrder, 'Keyboard reordering retains focus and order');
  // Holding a drag at the bottom edge scrolls long column lists automatically.
  await dialog.evaluate(element => { element.scrollTop = 0; });
  await taskGrip.scrollIntoViewIfNeeded();
  const dragBox = await taskGrip.boundingBox(), dialogBox = await dialog.boundingBox();
  const initialScroll = await dialog.evaluate(element => element.scrollTop);
  await page.mouse.move(dragBox.x + 14, dragBox.y + 14); await page.mouse.down();
  await page.mouse.move(dragBox.x + 14, dialogBox.y + dialogBox.height - 12, { steps: 8 });
  await page.waitForFunction(initial => document.querySelector('dialog[open]').scrollTop > initial + 30, initialScroll);
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.deepEqual(await order(), initialOrder);
  await beginDrag(page, dialog, 'Due', 'Reviewer');
  await page.mouse.up();
  assert.ok((await order()).indexOf('due') < (await order()).indexOf('reviewer'));
  assert.equal(await dialog.getByLabel('Show Reviewer', { exact: true }).isChecked(), false);
  assert.equal(await dialog.getByLabel('Show score', { exact: true }).isChecked(), true);
  await dialog.getByLabel('New view name', { exact: true }).fill('Daily review');
  await dialog.getByRole('button', { name: 'Save as new view', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  const titleHeader = page.locator('[data-plan-column="title"]');
  const sortBefore = await titleHeader.getAttribute('aria-sort');
  await resizeColumn(page, 'Task name', 120);
  await resizeColumn(page, 'Task name', -60);
  await resizeColumn(page, 'Task name', 60);
  assert.equal(await titleHeader.getAttribute('aria-sort'), sortBefore, 'Dragging must not sort the table');
  const handle = page.getByRole('separator', { name: 'Resize Task name column', exact: true });
  await handle.focus(); await page.keyboard.press('ArrowRight');
  await page.waitForFunction(() => document.querySelector('[aria-label="Resize Task name column"]')?.getAttribute('aria-disabled') === 'false');
  assert.equal(await handle.getAttribute('aria-valuenow'), '370');
  await handle.press('ArrowLeft');
  await page.waitForFunction(() => document.querySelector('[aria-label="Resize Task name column"]')?.getAttribute('aria-disabled') === 'false');
  const handleBox = await handle.boundingBox();
  await page.mouse.move(handleBox.x + 4, handleBox.y + 10); await page.mouse.down();
  await page.mouse.move(handleBox.x + 84, handleBox.y + 10);
  await page.keyboard.press('Escape'); await page.mouse.up();
  assert.equal(await handle.getAttribute('aria-valuenow'), '360', 'Escape cancels a drag');
  await page.screenshot({ path: `${artifactDir}/action-plan-resize-desktop.png` });
  assert.equal(await page.locator('[data-plan-column="reviewer"]').count(), 0);

  assert.deepEqual(await page.locator('[data-plan-column]').evaluateAll(els => els.slice(9, 12).map(el => el.dataset.planColumn)), ['editor', 'due', 'created'], 'Dragged order survives reload');
  assert.equal(await page.locator('[data-plan-cell="cf:score"]').innerText(), '0');
  assert.ok(Math.abs((await page.locator('[data-plan-column="title"]').boundingBox()).width - 360) < 2);
  assert.deepEqual(await page.locator('[data-plan-column]').evaluateAll((els) => els.slice(0, 4).map((el) => el.dataset.planColumn)), ['cb', 'source', 'title', 'origin']);
  assert.deepEqual(await page.locator('[data-plan-column]').evaluateAll((els) => els.slice(9, 12).map((el) => el.dataset.planColumn)), ['editor', 'due', 'created']);
  const id = await page.getByLabel('Action Plan saved view', { exact: true }).inputValue();
  await page.reload({ waitUntil: 'networkidle' });
  await page.waitForFunction((id) => document.querySelector('[aria-label="Action Plan saved view"]')?.value === id, id);
  assert.equal(await page.locator('[data-plan-column="reviewer"]').count(), 0);

  const peer = await context.newPage();
  await peer.goto(page.url(), { waitUntil: 'networkidle' }); await tab(peer, 'Action Plan');
  await peer.waitForFunction((id) => document.querySelector('[aria-label="Action Plan saved view"]')?.value === id, id);
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  await dialog.getByLabel('View name', { exact: true }).fill('Unsaved draft');
  const incoming = structuredClone(data.profiles[0].ap_col_state.qa_next);
  incoming.views.find((v) => v.id === id).name = 'Changed elsewhere';
  data.profiles[0].ap_col_state.qa_next = incoming;
  emit('profiles', 'UPDATE', data.profiles[0]);
  await peer.getByRole('option', { name: 'Changed elsewhere', exact: true }).waitFor({ state: 'attached' });
  assert.equal(await dialog.getByLabel('View name', { exact: true }).inputValue(), 'Unsaved draft');
  // Keep the draft but discard explicitly before a new edit against the latest version.
  await dialog.getByRole('button', { name: 'Close column preferences', exact: true }).click();
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  await dialog.getByLabel('View name', { exact: true }).fill('Renamed review');
  await dialog.getByRole('button', { name: 'Save layout', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  await peer.getByRole('option', { name: 'Renamed review', exact: true }).waitFor({ state: 'attached' });
  await peer.close();
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  await page.waitForFunction((id) => document.querySelector('[aria-label="Action Plan saved view"]')?.value === id, id);
  await page.locator('main > section').first().locator('select').selectOption('qa-fixture');
  await page.waitForFunction((id) => document.querySelector('[aria-label="Action Plan saved view"]')?.value === id, id);
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  await page.screenshot({ path: `${artifactDir}/action-plan-columns-desktop.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
  await dialog.evaluate(element => { element.scrollTop = 0; });
  const mobileOrder = await order();
  const touch = await context.newCDPSession(page);
  const sourceBox = await dialog.getByRole('button', { name: 'Drag Task name to reorder', exact: true }).boundingBox();
  const targetBox = await dialog.locator('[data-column-option="origin"]').boundingBox();
  const x = sourceBox.x + sourceBox.width / 2;
  await touch.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x, y: sourceBox.y + sourceBox.height / 2 }] });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x, y: targetBox.y + targetBox.height * 0.75 }] });
  assert.equal(await dialog.locator('[data-column-option="origin"]').getAttribute('data-drop'), 'after');
  await page.screenshot({ path: `${artifactDir}/column-drop-highlight-mobile.png` });
  await touch.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.deepEqual((await order()).slice(0, 4), ['cb', 'source', 'origin', 'title']);
  await touch.detach();
  // Discarded reorder drafts must not modify the saved view.
  await dialog.getByRole('button', { name: 'Close column preferences', exact: true }).click();
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  assert.deepEqual(await order(), mobileOrder);
  await page.screenshot({ path: `${artifactDir}/action-plan-columns-mobile.png`, fullPage: true });
  await dialog.getByRole('button', { name: 'Delete saved view', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(await page.getByLabel('Action Plan saved view', { exact: true }).inputValue(), 'default');
  await page.locator('[data-plan-column="reviewer"]').waitFor();
  assert.equal(await handle.getAttribute('aria-valuenow'), '240', 'Each saved view keeps its own widths');
  // Resize a visible narrow column on mobile, including minimum and maximum bounds.
  await resizeColumn(page, 'Selection', 40);
  await resizeColumn(page, 'Selection', -100);
  const selectionHandle = page.getByRole('separator', { name: 'Resize Selection column', exact: true });
  await selectionHandle.press('End');
  await page.waitForFunction(() => document.querySelector('[aria-label="Resize Selection column"]')?.getAttribute('aria-disabled') === 'false');
  assert.equal(await selectionHandle.getAttribute('aria-valuenow'), '600');
  await selectionHandle.press('Home');
  await page.waitForFunction(() => document.querySelector('[aria-label="Resize Selection column"]')?.getAttribute('aria-disabled') === 'false');
  assert.equal(await selectionHandle.getAttribute('aria-valuenow'), '44');
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifactDir}/action-plan-resize-mobile.png` });
  for (const width of [390, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    control.failNextPreferences = true;
    control.expectedPreferenceRejections = 1;
    await selectionHandle.press('ArrowRight');
    const notification = page.getByRole('alert').filter({ hasText: 'Could not save column layout' });
    await notification.waitFor();
    await page.waitForFunction(() => document.querySelector('[aria-label="Resize Selection column"]')?.getAttribute('aria-valuenow') === '44');
    assert.equal(data.profiles[0].ap_col_state.qa_next.views.find((view) => view.id === 'default').columns.find((column) => column.key === 'cb').width, 44);
    assert.equal(await notification.evaluate((element) => getComputedStyle(element).position), 'fixed');
    const bounds = await notification.boundingBox();
    assert.ok(bounds.y >= 0 && bounds.y <= 20 && bounds.x >= 0 && width - bounds.x - bounds.width <= 20);
    await page.screenshot({ path: `${artifactDir}/column-error-notification-${width}.png` });
    await page.getByRole('button', { name: 'Dismiss column notification', exact: true }).click();
    assert.equal(await notification.count(), 0);
    assert.equal(control.expectedPreferenceRejections, 0);
  }
  await resizeColumn(page, 'Selection', 10);
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await selectionHandle.getAttribute('aria-valuenow'), '54', 'Retry saves and survives reload');
  await page.getByRole('button', { name: 'Columns and views', exact: true }).click();
  await dialog.getByRole('button', { name: 'Save as new view', exact: true }).click();
  const validationNotice = dialog.getByRole('alert');
  await validationNotice.waitFor();
  assert.equal(await validationNotice.evaluate((element) => getComputedStyle(element).position), 'fixed');
  await dialog.getByRole('button', { name: 'Dismiss column notification', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close column preferences', exact: true }).click();
  assert.equal(data.manual_actions.length, 1); assert.equal(data.ads.length, 1);
  results.push('Action Plan column drag reorder with insertion highlights, touch and keyboard, auto-scroll, cancellation and draft discard; saved order/width/reload, server-valid resize, failure rollback/retry, dismissible errors, cross-tab draft preservation');
};
