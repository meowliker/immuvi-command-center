const assert = require('node:assert/strict');
module.exports = async function ({ page, data, emit, control, requests, tab, artifactDir, results }) {
  const target = { ...data.profiles_with_products[0], id: '22222222-2222-4222-8222-222222222222', email: 'access-fixture@example.test', role: 'member', product_ids: ['qa-fixture'] };
  data.profiles_with_products.push(target);
  await tab(page, 'Admin');
  const row = page.getByRole('article', { name: target.email, exact: true });
  const button = (name) => row.getByRole('button', { name, exact: true });
  await row.waitFor();
  assert.equal(await page.getByRole('article', { name: data.profiles[0].email, exact: true }).getByRole('button', { name: 'Make member', exact: true }).isDisabled(), true);
  assert.equal(await button('Save access').isDisabled(), true);
  await row.getByLabel('Second QA', { exact: true }).check();
  target.product_ids = []; target.accessGeneration = 1; emit('user_products', 'DELETE', { user_id: target.id, product_id: 'qa-fixture' });
  await button('Review latest access').waitFor();
  assert.equal(await row.getByLabel('QA Fixture', { exact: true }).isChecked(), true);
  assert.equal(await row.getByLabel('Second QA', { exact: true }).isChecked(), true);
  assert.equal(await button('Save access').isDisabled(), true);
  await button('Review latest access').click();
  control.loseAdminAccessAck = true;
  await button('Save access').click();
  await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const first = control.adminAccessCalls.at(-1);
  assert.equal(await page.getByRole('button', { name: 'Create user', exact: true }).isDisabled(), true);
  assert.equal(await button('Make admin').isDisabled(), true);
  await page.reload(); await tab(page, 'Admin');
  await page.getByRole('button', { name: 'Retry pending access change', exact: true }).click();
  await page.getByText(`Updated product access for ${target.email}.`, { exact: true }).waitFor();
  assert.deepEqual(control.adminAccessCalls.at(-1), first);
  assert.equal(control.adminAccessReceipts.size, 1);
  await button('Make admin').click();
  await button('Make member').waitFor();
  await button('Make member').click();
  await button('Make admin').waitFor();
  assert.deepEqual(target.product_ids, ['qa-fixture', 'qa-second']);
  await row.getByLabel('Second QA', { exact: true }).uncheck();
  target.accessGeneration++;
  control.expectedAdminAccessRejections = 1;
  await button('Save access').click();
  await page.getByRole('alert').filter({ hasText: 'User access changed' }).waitFor();
  await button('Review latest access').waitFor();
  assert.equal(await row.getByLabel('Second QA', { exact: true }).isChecked(), false);
  await button('Review latest access').click();
  await button('Save access').click();
  await page.getByText(`Updated product access for ${target.email}.`, { exact: true }).waitFor();
  assert.deepEqual(target.product_ids, ['qa-fixture']);
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `Overflow at ${width}`);
    if (width === 320 || width === 1440) await page.screenshot({ path: `${artifactDir}/admin-access-${width}.png`, fullPage: true });
  }
  assert.equal(requests.some((item) => ['user_products', 'profiles_with_products'].includes(item.table) && item.method !== 'GET'), false);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Admin access: stale draft preservation and explicit review, lost-ack replay across reload, global pending controls, self-role protection, immediate promotion/demotion, RPC-only writes and 320-1440px layouts');
};
