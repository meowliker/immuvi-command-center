const assert = require('node:assert/strict');
module.exports = async function testInspirationMutations({page,data,control,emit,tab,artifactDir,results}) {
  data.inspiration_queue=[];data.inspiration_results=[];
  await tab(page,'Inspiration');
  const button=(name)=>page.getByRole('button',{name,exact:true});
  const editor=()=>page.getByRole('dialog',{name:/^(Add manual inspiration|Edit inspiration:)/});
  const open=async(id)=>{await button(`Open inspiration ${id}`).click();};
  await page.getByLabel('Source URL',{exact:true}).fill('https://example.test/intake');
  control.loseInspirationAck=true;
  await button('+ Add to Queue').click();
  await button('Retry same save').waitFor();
  assert.equal(data.inspirations.length,1);assert.equal(data.inspiration_queue[0].status,'blocked');
  assert.equal(await page.getByLabel('Source URL',{exact:true}).isDisabled(),true);
  await button('Retry same save').click();
  await page.getByRole('dialog').waitFor({state:'detached'});
  assert.equal(data.inspirations.length,1);assert.equal(control.inspirationReceipts.size,1);
  await button('+ Manual').click();
  await editor().getByLabel('Source URL',{exact:true}).fill('https://example.test/manual');
  await page.getByLabel('Format name',{exact:true}).fill('Manual source');
  await page.getByLabel('Notes',{exact:true}).fill('Initial notes');
  for (const width of [320,390,768,1440]) {
    await page.setViewportSize({width,height:900});
    assert.equal(await editor().evaluate((el)=>el.scrollWidth<=el.clientWidth && el.getBoundingClientRect().left>=0 && el.getBoundingClientRect().right<=innerWidth),true);
    await page.screenshot({path:`${artifactDir}/inspiration-editor-${width}.png`});
  }
  await button('Save inspiration').click();await page.getByRole('dialog').waitFor({state:'detached'});
  const row=data.inspirations.find((item)=>item.title==='Manual source');
  row.data._clickupDocPageUrl='https://example.test/brief';row.data._dupeType='similar';row.data._dupeOf='Other source';
  Object.assign(data.ads[0],{format_name:row.title,meta:{_fromInspoId:row.id}});
  Object.assign(row.data,{angle:data.ads[0].angle,persona:data.ads[0].persona});
  emit('inspirations','UPDATE',row);emit('ads','UPDATE',data.ads[0]);
  await open(row.id);await page.getByRole('heading',{name:'Usage / 1 ads / 1 cells',exact:true}).waitFor();await button('Edit').click();
  await page.getByLabel('Format name',{exact:true}).fill('Renamed source');
  await page.getByLabel('Notes',{exact:true}).fill('');
  await button('Save inspiration').click();await editor().waitFor({state:'detached'});
  await page.getByRole('heading',{name:'Renamed source',exact:true}).waitFor();
  assert.equal(row.title,'Renamed source');assert.equal(row.data.notes,'');assert.equal(row.data._clickupDocPageUrl,'https://example.test/brief');
  assert.equal(data.ads[0].format_name,'Renamed source');assert.equal(data.manual_actions[0].payload.title,'Renamed source');
  await button('Edit').click();await page.getByLabel('Notes',{exact:true}).fill('My stale draft');
  row.updated_at='2099-01-01T00:00:00Z';row.data.notes='Updated elsewhere';emit('inspirations','UPDATE',row);control.expectedInspirationRejections=1;
  await button('Save inspiration').click();await page.getByRole('alert').filter({hasText:'Inspiration changed.'}).waitFor();
  assert.equal(await page.getByLabel('Notes',{exact:true}).inputValue(),'My stale draft');
  assert.equal(await page.getByLabel('Notes',{exact:true}).isDisabled(),false);
  await button('Cancel').click();
  await page.getByRole('dialog').getByText('Updated elsewhere',{exact:true}).waitFor();
  await button('Approve').click();await button('Approve inspiration').click();await page.getByRole('dialog',{name:'Approve inspiration',exact:true}).waitFor({state:'detached'});
  assert.equal(row.status,'Approved');
  await page.waitForLoadState('networkidle');
  await button('Review duplicate').click();await button('Mark duplicate reviewed').click();await button('Reviewed').waitFor();
  assert.equal(row.data._dupeType,'similar');assert.equal(row.data._dupeBannerDismissed,true);
  data.inspiration_results=[{id:'result-test',ins_id:row.id,product_id:row.product_id,source_url:row.url,classified_at:'2099-01-01T00:00:00Z',classification:{creative_usp:'Imported source'},brief:{}}];
  await button('Import result').click();await page.getByLabel('Classification result',{exact:true}).waitFor();control.expectedInspirationRejections=1;
  await button('Import classification result').click();await page.getByRole('alert').filter({hasText:'Eight-section brief is incomplete'}).waitFor();
  await button('Cancel').click();
  data.inspiration_results[0].brief={next_ad_scripts:[{variation:'A'},{variation:'B'},{variation:'C'}],why_it_works:'Test'};
  await button('Import result').click();await page.getByLabel('Classification result',{exact:true}).waitFor();
  await button('Import classification result').click();await page.getByRole('dialog',{name:'Import classification result',exact:true}).waitFor({state:'detached'});
  assert.equal(row.title,'Imported source');assert.equal(data.ads[0].format_name,'Imported source');assert.equal(row.data._classificationBrief.why_it_works,'Test');
  assert.equal(row.data._clickupDocPageUrl,'https://example.test/brief');
  await page.getByRole('heading',{name:'Imported source',exact:true}).waitFor();
  await button('Requeue').click();await button('Requeue inspiration').click();await page.getByRole('dialog',{name:'Requeue inspiration',exact:true}).waitFor({state:'detached'});
  assert.equal(row.status,'Blocked');assert.equal(data.inspiration_queue.find((q)=>q.ins_id===row.id).worker_assignment,'blocked:qa-isolation');
  await page.waitForLoadState('networkidle');
  await button('Delete').click();await button('Cancel').click();assert.equal(data.inspirations.includes(row),true);
  await button('Delete').click();await button('Delete inspiration').click();await page.getByRole('dialog').first().waitFor({state:'detached'});
  assert.equal(data.inspirations.includes(row),false);assert.equal(data.inspiration_results.length,0);assert.equal(data.ads[0].format_name,'Imported source');
  assert.equal(control.clickupCalls.length,0);assert.equal(new URL(page.url()).pathname,'/');
  results.push('Inspiration mutations: URL intake with lost-ack replay exactly once, manual intake, 320/390/768/1440px editor bounds, rename cascade, field clearing, brief preservation, stale draft retention, approval, duplicate review, incomplete/complete result import, blocked requeue, cancel/delete preserving creatives; no classifier or external calls');
};
