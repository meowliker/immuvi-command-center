const assert=require('node:assert/strict');
module.exports=async function testMatrixInspector({page,data,tab,artifactDir,results}) {
  const stamp=new Date().toISOString();
  const first=data.ads[0];
  first.status='Testing';first.created_at=stamp;
  first.meta={...first.meta,creativeUSP:'A complete creative USP '.repeat(20),notes:'Testing note',dueDate:'2026-10-01'};
  data.ads.push({...structuredClone(first),id:'READY',format_name:'Ready example',status:'Ready to Launch',ad_origin:'From Inspo',funnel_stage:'MOF',created_at:'2025-01-01T12:00:00Z',meta:{_fromInspoId:'INS-TEST',_customFields:{Editor:'QA editor'}}});
  data.inspirations.push({id:'INS-TEST',product_id:'qa-fixture',title:'Test reference',status:'Classified',url:'https://example.test/inspiration',data:{},updated_at:stamp});
  data.angles.push({...data.angles[0],id:'ANG-2',name:'Health'});
  await tab(page,'Creative Matrix');
  await page.getByRole('button',{name:'Energy x Busy people: 2 creatives',exact:true}).click();
  const dialog=page.getByRole('dialog'),table=dialog.getByRole('region',{name:'Cell creative table'});
  assert.deepEqual(await dialog.getByRole('tab').allTextContents(),['Creatives 2','+ Add Creative','Insights']);
  const expected=['Source','Task name','Type','Funnel','Origin','Created','Due','Status','Angle / Persona','Inspiration','Creative USP','Notes','Action',''];
  assert.deepEqual(await table.locator('th').allTextContents(),expected);
  assert.equal(await table.getByRole('columnheader',{name:'Created',exact:true}).getAttribute('aria-sort'),'descending');
  await table.getByRole('button',{name:'Created',exact:true}).click();
  assert.equal(await table.locator('tbody tr').first().getAttribute('data-cell-creative'),'READY');
  assert.equal(await table.getByRole('columnheader',{name:'Created',exact:true}).getAttribute('aria-sort'),'ascending');
  assert.equal(await table.getByRole('link',{name:'INS-TEST'}).getAttribute('href'),'https://example.test/inspiration');
  assert.equal(await table.getByLabel('Matrix status for Ready example').evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(255, 226, 102)');
  assert.equal(await table.getByLabel(`Matrix status for ${first.format_name}`).evaluate(el=>getComputedStyle(el).backgroundColor),'rgb(200, 184, 255)');
  await dialog.getByLabel('Cell date filter').selectOption('today');
  assert.equal(await table.locator('[data-cell-creative]').count(),1);
  await dialog.getByLabel('Cell date filter').selectOption('all');
  await dialog.getByLabel('Cell status filter',{exact:true}).click();
  await dialog.getByRole('checkbox',{name:'Testing',exact:true}).check();
  assert.equal(await table.locator('[data-cell-creative]').count(),1);
  await page.keyboard.press('Escape');assert.equal(await dialog.isVisible(),true);
  await dialog.getByRole('button',{name:'Reset filters',exact:true}).click();
  await dialog.getByLabel('Cell funnel filter',{exact:true}).click();
  await dialog.getByRole('checkbox',{name:'MOF',exact:true}).check();
  assert.equal(await table.locator('[data-cell-creative]').count(),1);
  await page.keyboard.press('Escape');
  await dialog.getByRole('button',{name:'Reset filters',exact:true}).click();
  await dialog.getByLabel('Search cell creatives').fill('Testing note');
  assert.equal(await table.locator('[data-cell-creative]').count(),1);
  await dialog.getByLabel('Search cell creatives').fill('');
  await dialog.getByLabel('Cell columns',{exact:true}).click();
  await dialog.getByRole('checkbox',{name:'Notes',exact:true}).uncheck();
  await dialog.getByRole('checkbox',{name:'Editor CU',exact:true}).check();
  assert.equal(await table.getByRole('columnheader',{name:'Notes',exact:true}).count(),0);
  assert.equal(await table.getByRole('columnheader',{name:'Editor',exact:true}).count(),1);
  await page.keyboard.press('Escape');
  await dialog.getByLabel('Cell saved views',{exact:true}).click();
  await dialog.getByLabel('Cell view name').fill('QA columns');
  await dialog.getByRole('button',{name:'Save current view',exact:true}).click();
  await dialog.getByLabel('Cell saved views',{exact:true}).click();
  await dialog.getByRole('button',{name:'Default view',exact:true}).click();
  assert.deepEqual(await table.locator('th').allTextContents(),expected);
  for(const width of [1440,768,390,320]) {
    await page.setViewportSize({width,height:900});
    await table.evaluate(el=>{el.scrollLeft=0;});
    assert.equal(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth),true,'Dialog must not overflow');
    assert.ok((await dialog.boundingBox()).height<=880);
    assert.ok((await table.locator('tbody tr').first().boundingBox()).height<100,'Rows must remain compact');
    await dialog.getByLabel('Cell columns',{exact:true}).click();
    const menu=dialog.getByLabel('Search cell columns');
    assert.ok((await menu.boundingBox()).x>=0 && (await menu.boundingBox()).x+(await menu.boundingBox()).width<=width);
    await page.keyboard.press('Escape');
    await page.screenshot({path:`${artifactDir}/matrix-cell-${width}.png`});
    await table.evaluate(el=>{el.scrollLeft=el.scrollWidth;});
    assert.ok(await table.evaluate(el=>el.scrollLeft>0));
    await page.screenshot({path:`${artifactDir}/matrix-cell-right-${width}.png`});
  }
  await page.setViewportSize({width:1440,height:900});
  await dialog.getByRole('tab',{name:'Insights',exact:true}).click();
  assert.equal(await dialog.getByRole('tabpanel',{name:'Insights'}).isVisible(),true);
  await dialog.getByRole('tab',{name:'+ Add Creative',exact:true}).click();
  for(const name of ['Creative Tracker','From Inspiration','Blank Brief']) assert.equal(await dialog.getByRole('button',{name,exact:true}).isVisible(),true);
  await dialog.getByRole('button',{name:'Close inspector'}).click();
  await page.reload({waitUntil:'networkidle'});
  await page.getByRole('button',{name:'Energy x Busy people: 2 creatives',exact:true}).click();
  await dialog.getByLabel('Cell saved views',{exact:true}).click();
  await dialog.getByRole('button',{name:'QA columns',exact:true}).click();
  assert.equal(await table.getByRole('columnheader',{name:'Editor',exact:true}).count(),1);
  await dialog.getByLabel('Cell saved views',{exact:true}).click();
  await dialog.getByRole('button',{name:'Default view',exact:true}).click();
  await table.getByLabel(`Task name for ${first.format_name}`).fill('Renamed in cell');
  await page.keyboard.press('Enter');
  await table.getByLabel('Task name for Renamed in cell').waitFor();
  assert.equal(first.format_name,'Renamed in cell');
  await table.getByLabel('Matrix due date for Renamed in cell').fill('2026-10-20');
  await page.waitForFunction(()=>document.querySelector('[aria-label="Matrix due date for Renamed in cell"]')?.disabled===false);
  assert.equal(first.meta.dueDate,'2026-10-20');
  await table.getByLabel('Matrix angle for Renamed in cell').selectOption('Health');
  await table.getByRole('button',{name:'Save taxonomy for Renamed in cell'}).click();
  await table.getByLabel('Task name for Renamed in cell').waitFor({state:'detached'});
  assert.equal(first.angle,'Health');
  await table.getByRole('button',{name:'Delete Ready example',exact:true}).click();
  await dialog.getByRole('button',{name:'Back to cell',exact:true}).click();
  assert.equal(await table.locator('[data-cell-creative="READY"]').count(),1,'Backing out of delete must retain the creative');
  await dialog.getByRole('button',{name:'Close inspector'}).click();
  results.push('Legacy cell popup: exact 14 default columns, 3 tabs, pastel status colors, compact responsive table, sorting, date/status/funnel/search filters, custom-field visibility, persisted local saved views, rename/due/taxonomy saves and cancel deletion; mocked QA only');
};
