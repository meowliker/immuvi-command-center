const assert = require('node:assert/strict');
module.exports = async function testProductAdministration({ page, data, emit, control, requests, tab, artifactDir, results }) {
  await tab(page, 'COMMAND HQ');
  const toolbar = page.getByRole('group', { name: 'Product administration' });
  const button = (name) => page.getByRole('button', { name, exact: true });
  const calls = () => control.productAdminCalls || [];
  const dialog = page.getByRole('dialog');
  await button('Add Product').click();
  await dialog.getByLabel('Product name', { exact: true }).fill('QA disposable product');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(calls().length, 0);
  await button('Add Product').click();
  await dialog.getByLabel('Product name', { exact: true }).fill('QA disposable product');
  control.loseProductAck = true;
  await dialog.getByRole('button', { name: 'Save product', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const create = calls().at(-1);
  await page.reload();
  await button('Retry same request').click();
  await page.getByText('Product create saved in QA.', { exact: true }).waitFor();
  assert.deepEqual(calls().at(-1), create); assert.equal(data.products.length, 3);
  await button('Manage Fields').click();
  await dialog.getByLabel('Creative structure option 1', { exact: true }).fill('Product-specific structure');
  await dialog.getByLabel('Creative structure description 1', { exact: true }).fill('A preserved description');
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
    const box = await dialog.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= width);
    await page.screenshot({ path: `${artifactDir}/product-fields-${width}.png`, fullPage: true });
  }
  data.products[0].updated_at = new Date(Date.now() + 10000).toISOString(); emit('products', 'UPDATE', data.products[0]);
  control.expectedProductRejections = 1;
  await dialog.getByRole('button', { name: 'Save product', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'Product changed' }).waitFor();
  assert.equal(await dialog.getByLabel('Creative structure option 1', { exact: true }).inputValue(), 'Product-specific structure');
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.waitForTimeout(350);
  await button('Manage Fields').click();
  await dialog.getByLabel('Creative structure option 1', { exact: true }).fill('Product-specific structure');
  await dialog.getByLabel('Creative structure description 1', { exact: true }).fill('A preserved description');
  await dialog.getByRole('button', { name: 'Move Product-specific structure down', exact: true }).click();
  await dialog.getByRole('button', { name: 'Remove Testimonial', exact: true }).click();
  await dialog.getByRole('button', { name: 'Save product', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  await page.locator('[data-hq-coverage="creativeStructure"]').getByText('Product-specific structure', { exact: true }).waitFor();
  assert.equal(data.products[0].config.clickup_list_id, '1301130000002447');
  assert.equal(data.products[1].config.field_options, undefined);
  await tab(page, 'Creative Tracker');
  await button('Edit QA creative').click();
  const list = await dialog.getByLabel('Creative structure', { exact: true }).getAttribute('list');
  assert.ok(list); assert.ok((await dialog.locator('datalist option').evaluateAll((options) => options.map((o) => o.value))).includes('Product-specific structure'));
  await dialog.getByRole('button', { name: 'Close editor', exact: true }).click();
  await tab(page, 'COMMAND HQ');
  await button('Unlink').click();
  assert.equal(await dialog.getByRole('button', { name: 'Save product', exact: true }).isDisabled(), true);
  await dialog.getByLabel('Type product name').fill('QA Fixture');
  await dialog.getByRole('button', { name: 'Save product', exact: true }).click();
  await dialog.waitFor({ state: 'detached' });
  assert.equal(data.products[0].config.clickup_list_id, undefined); assert.equal(data.ads.length, 1);
  await button('Delete').click();
  await dialog.getByRole('button', { name: 'Preview deletion', exact: true }).click();
  await dialog.getByText('Queued or running work blocks deletion.', { exact: true }).waitFor();
  await dialog.getByLabel('Type product name').fill('QA Fixture');
  assert.equal(await dialog.getByRole('button', { name: 'Delete product permanently', exact: true }).isDisabled(), true);
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.locator('main > section').first().locator('select').selectOption(create.p_product_id);
  await button('Delete').click();
  await dialog.getByRole('button', { name: 'Preview deletion', exact: true }).click();
  await dialog.getByRole('button', { name: 'Refresh deletion preview', exact: true }).waitFor();
  await dialog.getByLabel('Type product name').fill('QA disposable product');
  data.ads.push({ id: 'late-creative', product_id: create.p_product_id, format_name: 'Late creative', meta: {} });
  control.expectedProductRejections = 1;
  await dialog.getByRole('button', { name: 'Delete product permanently', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'Product data changed since preview' }).waitFor();
  await dialog.getByRole('button', { name: 'Refresh deletion preview', exact: true }).click();
  await dialog.locator('dt').filter({ hasText: /^ads$/ }).waitFor();
  control.loseProductAck = true;
  await dialog.getByRole('button', { name: 'Delete product permanently', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const removal = calls().at(-1);
  await page.reload(); await button('Retry same request').click();
  await page.getByText('Product delete saved in QA.', { exact: true }).waitFor();
  assert.deepEqual(calls().at(-1), removal); assert.equal(data.products.length, 2); assert.equal(data.ads.length, 1);
  assert.equal(control.clickupCalls.length, 0);
  assert.equal(requests.some((request) => request.table === 'products' && request.method !== 'GET'), false);
  assert.equal(new URL(page.url()).pathname, '/');
  results.push('Product administration: create/delete lost-ack recovery across reload, scoped field options and editor/HQ propagation, stale-draft rejection, confirmed unlink preserving creatives, deletion counts/change/queued-work guards, 320-1440px dialogs, RPC-only mutations and no external dispatch');
};
module.exports.member = async function ({ page, tab, results }) {
  await tab(page, 'COMMAND HQ');
  for (const name of ['Add Product','Manage Fields','Delete','Unlink']) assert.equal(await page.getByRole('button', { name, exact: true }).count(), 0);
  results.push('Product administration controls are absent for members');
};
