const assert = require('node:assert/strict');

module.exports = async function testTaxonomyMutations({ page, data, emit, control, requests, tab, artifactDir, results }) {
  await tab(page, 'Angles');
  const original = page.locator('[data-taxonomy-id="ANG-1"]');
  const calls = () => control.taxonomyCalls || [];
  // A create that committed but lost its reply must survive reload without a duplicate.
  control.loseTaxonomyAck = true;
  await page.getByRole('button', { name: 'Add Angle', exact: true }).click();
  await page.getByRole('button', { name: 'Retry same request', exact: true }).waitFor();
  await page.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const createRequest = calls()[0];
  assert.equal(await page.getByRole('button', { name: 'Add Angle', exact: true }).isDisabled(), true);
  await page.reload(); await tab(page, 'Angles');
  await page.getByRole('button', { name: 'Retry same request', exact: true }).click();
  await page.getByText('Angle create saved in QA.', { exact: true }).waitFor();
  assert.deepEqual(calls()[1], createRequest);
  assert.equal(data.angles.length, 2);
  const created = data.angles.find((row) => row.id !== 'ANG-1');
  const secondary = page.locator(`[data-taxonomy-id="${created.id}"]`);
  await secondary.locator('input').nth(0).fill('Focus');
  await secondary.locator('input').nth(1).fill('https://example.test/taxonomy');
  await secondary.locator('textarea').fill('Losing notes must survive');
  await secondary.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Angle save saved in QA.', { exact: true }).waitFor();
  assert.equal(created.name, 'Focus');
  // A draft must keep the version it was based on, even after realtime rebasing.
  await original.locator('textarea').fill('My retained draft');
  data.angles[0].notes = 'Another editor changed these notes';
  data.angles[0].updated_at = new Date(Date.now() + 2000).toISOString();
  emit('angles', 'UPDATE', data.angles[0]);
  await original.getByRole('button', { name: 'Review latest version', exact: true }).waitFor();
  control.expectedTaxonomyRejections = 1;
  await original.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Taxonomy changed' }).waitFor();
  assert.equal(await original.locator('textarea').inputValue(), 'My retained draft');
  assert.equal(data.angles[0].notes, 'Another editor changed these notes');
  await original.getByRole('button', { name: 'Review latest version', exact: true }).click();
  await original.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Taxonomy changed' }).waitFor({ state: 'hidden' });
  await page.waitForFunction(() => ![...document.querySelectorAll('button')].find((node) => node.textContent === 'Merge Angles')?.disabled);
  assert.equal(data.angles[0].notes, 'My retained draft');
  data.ads[0].angle = 'Focus'; emit('ads', 'UPDATE', data.ads[0]);
  data.inspirations.push({ id: 'taxonomy-inspiration', product_id: created.product_id, data: { angle: 'Focus' } });
  data.manual_actions[0].payload.sourceAngle = 'Focus';
  await page.getByRole('button', { name: 'Merge Angles', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Merge angles', exact: true });
  await dialog.getByLabel('Keep taxonomy entry').selectOption('ANG-1');
  await dialog.getByRole('checkbox', { name: 'Focus', exact: true }).check();
  const beforeCancel = calls().length;
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(calls().length, beforeCancel);
  await page.getByRole('button', { name: 'Merge Angles', exact: true }).click();
  await dialog.getByLabel('Keep taxonomy entry').selectOption('ANG-1');
  await dialog.getByRole('checkbox', { name: 'Focus', exact: true }).check();
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    const box = await dialog.boundingBox(); assert.ok(box.x >= 0 && box.x + box.width <= width);
    assert.equal(await dialog.evaluate((el) => el.scrollWidth <= el.clientWidth), true);
    await page.screenshot({ path: `${artifactDir}/taxonomy-merge-${width}.png`, fullPage: true });
  }
  control.taxonomyConflict = true; control.expectedTaxonomyRejections = 1;
  await dialog.getByRole('button', { name: 'Merge', exact: true }).click();
  await dialog.getByRole('alert').filter({ hasText: 'Matrix metadata conflicts' }).waitFor();
  assert.equal(data.angles.length, 2); assert.equal(data.ads[0].angle, 'Focus');
  control.taxonomyConflict = false; control.loseTaxonomyAck = true;
  await dialog.getByRole('button', { name: 'Merge', exact: true }).click();
  await dialog.getByRole('button', { name: 'Retry same request', exact: true }).waitFor();
  await dialog.getByRole('alert').filter({ hasText: 'could not be verified' }).waitFor();
  const mergeRequest = calls().at(-1);
  assert.equal(await dialog.getByRole('checkbox', { name: 'Focus', exact: true }).isDisabled(), true);
  await page.reload(); await tab(page, 'Angles');
  await page.getByRole('button', { name: 'Retry same request', exact: true }).click();
  await page.getByText('Angle merge saved in QA.', { exact: true }).waitFor();
  assert.deepEqual(calls().at(-1), mergeRequest);
  assert.equal(data.angles.length, 1); assert.equal(data.ads[0].angle, 'Energy');
  assert.equal(data.inspirations[0].data.angle, 'Energy'); assert.equal(data.manual_actions[0].payload.sourceAngle, 'Energy');
  assert.ok(data.angles[0].notes.includes('Losing notes must survive'));
  await original.getByRole('button', { name: 'Archive', exact: true }).click();
  await page.getByText('No angles in this view.', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Archived', exact: true }).click();
  await original.getByRole('button', { name: 'Restore', exact: true }).click();
  await page.getByRole('button', { name: 'Active', exact: true }).click();
  await original.waitFor();
  const beforeDelete = calls().length;
  page.removeAllListeners('dialog'); page.once('dialog', (message) => message.dismiss());
  await original.getByRole('button', { name: 'Delete', exact: true }).click();
  assert.equal(calls().length, beforeDelete);
  page.on('dialog', (message) => message.accept());
  await original.getByRole('button', { name: 'Delete', exact: true }).click();
  await page.getByText('No angles in this view.', { exact: true }).waitFor();
  assert.equal(data.ads[0].angle, ''); assert.equal(data.ads.length, 1);
  await tab(page, 'Personas');
  const persona = page.locator('[data-taxonomy-id="PER-1"]');
  await persona.locator('textarea').fill('Keep these unsaved persona notes');
  const removedPersona = data.personas.shift(); emit('personas', 'DELETE', removedPersona);
  const retained = page.getByRole('region', { name: 'Unavailable taxonomy drafts', exact: true });
  await retained.waitFor();
  await retained.locator('summary').click();
  await retained.getByText('Keep these unsaved persona notes', { exact: true }).waitFor();
  await page.getByRole('button', { name: 'Refresh', exact: true }).click();
  await retained.getByText('Keep these unsaved persona notes', { exact: true }).waitFor();
  await retained.getByRole('button', { name: 'Discard draft', exact: true }).click();
  await retained.waitFor({ state: 'hidden' });
  control.holdTaxonomy = true;
  await page.getByRole('button', { name: 'Add Persona', exact: true }).click();
  for (let i = 0; !control.releaseTaxonomy && i < 100; i++) await page.waitForTimeout(10);
  assert.equal(typeof control.releaseTaxonomy, 'function');
  assert.equal(await page.getByRole('button', { name: 'Adding...', exact: true }).isDisabled(), true);
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  control.releaseTaxonomy(); control.releaseTaxonomy = null;
  await page.getByText('No personas in this view.', { exact: true }).waitFor();
  assert.equal(await page.getByText('Persona create saved in QA.', { exact: true }).count(), 0);
  assert.equal(new URL(page.url()).pathname, '/');
  assert.equal(control.clickupCalls.length, 0);
  assert.equal(requests.some((request) => ['ads', 'angles', 'personas', 'inspirations', 'manual_actions', 'matrix_cells'].includes(request.table) && request.method !== 'GET'), false);
  results.push('Atomic taxonomy UI: durable create/merge same-request recovery across reload, stale draft rejection and explicit review, retained drafts after external deletion, confirmed merge/cancel/conflict, preserved notes, archive/restore/delete cancel/cascade, busy and late-product guards, 320-1440px dialogs, RPC-only writes and no external dispatch');
};
