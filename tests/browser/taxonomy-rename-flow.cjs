const assert = require('node:assert/strict');
module.exports = async function testTaxonomyRename({ page, data, control, tab, results }) {
  data.inspirations.push({ id: 'rename-ins', product_id: 'qa-fixture', data: { angle: 'Energy', persona: 'Busy people' } });
  await tab(page, 'Angles');
  const row = page.locator('[data-taxonomy-id="ANG-1"]');
  const calls = () => (control.taxonomyCalls || []).length;
  await row.locator('input').first().fill('Focus');
  page.removeAllListeners('dialog');
  let message;
  page.once('dialog', async (dialog) => { message = dialog.message(); await dialog.dismiss(); });
  await row.getByRole('button', { name: 'Save', exact: true }).click();
  for (let i = 0; !message && i < 100; i++) await page.waitForTimeout(10);
  await row.getByRole('button', { name: 'Save', exact: true }).waitFor();
  await page.waitForFunction(() => !document.querySelector('[data-taxonomy-id="ANG-1"] button[title="Save"]')?.disabled);
  assert.match(message, /Affected creatives\/tasks: 1\nInspirations: 1\nAction Plan records: 1/);
  assert.equal(calls(), 0); assert.equal(data.angles[0].name, 'Energy');
  control.invalidRenamePreview = true;
  await row.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Rename preview could not be verified' }).waitFor();
  assert.equal(calls(), 0); assert.equal(await row.locator('input').first().inputValue(), 'Focus');
  // A dependent row changes during confirmation, with unchanged affected counts.
  control.expectedTaxonomyRejections = 1;
  page.once('dialog', async (dialog) => { data.ads[0].meta.otherEditor = 'changed'; await dialog.accept(); });
  await row.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Rename impact changed' }).waitFor();
  assert.equal(data.angles[0].name, 'Energy'); assert.equal(data.ads[0].angle, 'Energy');
  assert.equal((control.taxonomyAudit || []).length, 0);
  page.on('dialog', (dialog) => dialog.accept());
  control.loseTaxonomyAck = true;
  await row.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByRole('button', { name: 'Retry same request', exact: true }).waitFor();
  const request = structuredClone(control.taxonomyCalls.at(-1));
  assert.match(request.p_values.renameRevision, /^[a-f0-9]{32}$/);
  assert.equal(control.taxonomyAudit.length, 1);
  await page.reload(); await tab(page, 'Angles');
  await page.getByRole('button', { name: 'Retry same request', exact: true }).click();
  await page.getByText('Angle save saved in QA.', { exact: true }).waitFor();
  assert.deepEqual(control.taxonomyCalls.at(-1), request); assert.equal(control.taxonomyAudit.length, 1);
  assert.equal(control.taxonomyAudit[0].beforeName, 'Energy'); assert.equal(control.taxonomyAudit[0].afterName, 'Focus');
  assert.equal(data.ads[0].angle, 'Focus'); assert.equal(data.inspirations[0].data.angle, 'Focus');
  await page.setViewportSize({ width: 390, height: 844 });
  await tab(page, 'Personas');
  const persona = page.locator('[data-taxonomy-id="PER-1"]');
  await persona.locator('input').first().fill('Students');
  await persona.getByRole('button', { name: 'Save', exact: true }).click();
  await page.getByText('Persona save saved in QA.', { exact: true }).waitFor();
  assert.equal(data.ads[0].persona, 'Students'); assert.equal(control.taxonomyAudit.length, 2);
  // A late preview must not prompt or save after changing products.
  await persona.locator('input').first().fill('Graduates');
  control.holdRenamePreview = true;
  await persona.getByRole('button', { name: 'Save', exact: true }).click();
  for (let i = 0; !control.releaseRenamePreview && i < 100; i++) await page.waitForTimeout(10);
  assert.equal(typeof control.releaseRenamePreview, 'function');
  const beforeLate = calls(); let lateDialog = false;
  page.removeAllListeners('dialog'); page.on('dialog', async (dialog) => { lateDialog = true; await dialog.dismiss(); });
  await page.locator('main > section').first().locator('select').selectOption('qa-second');
  control.releaseRenamePreview();
  await page.waitForLoadState('networkidle');
  assert.equal(lateDialog, false); assert.equal(calls(), beforeLate); assert.equal(data.personas[0].name, 'Students');
  assert.equal(control.clickupCalls.length, 0);
  results.push('Rename impact: verified database-preview counts, no-write cancel/invalid preview, unchanged-count stale snapshot rejection, atomic provenance, exact lost-ack recovery across reload, persona mobile save and late-product cancellation; no external dispatch');
};
